#!/usr/bin/env python
"""aggregate_e2_governance.py — E2 verdict: collect per-detector FP-reduction
benchmark JSONs (produced by tools/eval_fp_reduction_benchmark.py on each
comparison detector's governance_features) and decide the DETECTOR-AGNOSTIC
governance claim.

Per detector we extract, at matched TP-retention:
    M0          = M0_score      fp_supp   (score-only baseline)
    KG-gate     = KG-gate-MLP   fp_supp   (governance, "ours")
    gain        = KG-gate - M0              (the model-level contribution)

Verdict: governance is DETECTOR-AGNOSTIC if gain > 0 on >= MIN_AGNOSTIC
detectors (default 2). This is the E2 gate from the runbook.

Outputs (fresh timestamped dir — never overwrites a prior aggregation):
    e2_governance_summary.json
    T11_e2_governance.tex        (copy into journal/tables/ when satisfied)
    e2_detector_agnostic.md

Reads ONLY benchmark JSONs; does not touch Mode 1.

Usage:
    # explicit name=path (recommended; names control the table rows):
    python tools/aggregate_e2_governance.py \
        --bench "Faster R-CNN (ours)=outputs/detcmp/fasterrcnn_fp_benchmark.json" \
        --bench "RetinaNet=outputs/detcmp/retinanet_fp_benchmark.json" \
        --bench "FCOS=outputs/detcmp/fcos_fp_benchmark.json"
    # or glob (detector name derived from filename <name>_fp_benchmark.json):
    python tools/aggregate_e2_governance.py --glob "outputs/detcmp/*_fp_benchmark.json"
"""
from __future__ import annotations

import argparse
import glob as _glob
import json
import sys
from pathlib import Path

_here = Path(__file__).resolve().parent
_root = _here.parent
if str(_root) not in sys.path:
    sys.path.insert(0, str(_root))

from tools._safe_output import fresh_timestamped_dir  # noqa: E402

M0_METHOD = "M0_score"
KG_METHOD_SUBSTR = "KG-gate"  # matches "KG-gate-MLP (ours)"


def _find(results, predicate):
    for r in results:
        if predicate(r.get("method", "")):
            return r
    return None


def _fmt(x):
    if x is None:
        return "[--]"
    try:
        if x != x:
            return "[--]"
        return f"{float(x):.3f}"
    except (TypeError, ValueError):
        return "[--]"


def _signed(x):
    if x is None or x != x:
        return "[--]"
    return f"{x:+.3f}"


def load_bench(name: str, path: str) -> dict:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    results = payload.get("results", [])
    m0 = _find(results, lambda m: m == M0_METHOD)
    kg = _find(results, lambda m: KG_METHOD_SUBSTR in m)
    m0_fp = m0.get("fp_supp") if m0 else None
    kg_fp = kg.get("fp_supp") if kg else None
    fp_gain = (kg_fp - m0_fp) if (kg_fp is not None and m0_fp is not None) else None
    m0_auprc = (m0 or {}).get("auprc")
    kg_auprc = (kg or {}).get("auprc")
    bs = payload.get("bootstrap") or {}                    # FP-supp bootstrap
    bsa = (payload.get("bootstrap_auprc") or {}).get("kg_minus_m0") or {}  # AUPRC bootstrap
    # PRIMARY metric = threshold-free AUPRC gain (the FP-suppression gain is
    # sensitive to TP-retention mismatch on test, so it is reported as secondary).
    auprc_gain = bsa.get("gain_point")
    if auprc_gain is None and (m0_auprc is not None and kg_auprc is not None):
        auprc_gain = kg_auprc - m0_auprc
    return {
        "detector": name, "source": str(path),
        "positive_label": payload.get("positive_label"),
        "tp_ret_target": payload.get("tp_ret_target"),
        "n_test_boxes": payload.get("n_test_boxes"),
        # PRIMARY: AUPRC gain (threshold-free, comparable)
        "gain": auprc_gain,
        "gain_ci95": bsa.get("gain_ci95"),
        "gain_p_gt0": bsa.get("p_gain_gt0"),
        "gain_sig": bsa.get("sig"),
        "m0_auprc": m0_auprc, "kg_auprc": kg_auprc,
        # SECONDARY: FP-suppression gain (TP-mismatch sensitive — context only)
        "fp_gain": fp_gain, "m0_fp_supp": m0_fp, "kg_fp_supp": kg_fp,
        "fp_gain_ci95": bs.get("gain_ci95"), "fp_gain_sig": bs.get("sig"),
        "m0_precision": (m0 or {}).get("precision_after"),
        "kg_precision": (kg or {}).get("precision_after"),
        "n_bootstrap": bsa.get("n_bootstrap") or bs.get("n_bootstrap"),
    }


def _ci(r, key="gain_ci95"):
    c = r.get(key)
    if not c:
        return "[--]"
    return f"[{c[0]:+.3f}, {c[1]:+.3f}]"


def _fpci(r):
    c = r.get("fp_gain_ci95")
    return f"[{c[0]:+.3f}, {c[1]:+.3f}]" if c else "[--]"


def render_tex(rows, verdict: dict) -> str:
    head = (
        "% T11 — E2 detector-agnostic governance (auto-generated by\n"
        "% tools/aggregate_e2_governance.py). PRIMARY metric = threshold-free AUPRC\n"
        "% gain (KG-gate - M0). FP-suppression gain is shown for context only: it is\n"
        "% sensitive to TP-retention mismatch on test, so it is NOT the headline.\n"
        "\\begin{table}[t]\n\\centering\n"
        "\\caption{Detector-agnostic governance (E2). The same KG-evidence "
        "governance gate is applied on top of each detector's detections on the same "
        "OIA-DDR split (retain-vs-suppress triage task). The comparison metric is the "
        "threshold-free AUPRC gain $\\Delta_{\\mathrm{AUPRC}}$ over the score-only "
        "baseline; a positive value across architectures evidences a detector-agnostic "
        "contribution. The operating-point FP-suppression gain is shown for context "
        "only (it is sensitive to TP-retention mismatch and is not the headline).}\n"
        "\\label{tab:e2_governance}\n"
        "\\begin{tabular}{lcccc c}\n\\toprule\n"
        "Detector & M0 AUPRC & +Gov.\\ AUPRC & $\\Delta_{\\mathrm{AUPRC}}$ & 95\\% CI & FP-suppr.\\ $\\Delta^{\\dagger}$ \\\\\n"
        "\\midrule\n"
    )
    body = []
    for r in rows:
        ci = _ci(r) if r.get("gain_ci95") else "--"
        body.append(
            f"{r['detector']} & {_fmt(r['m0_auprc'])} & {_fmt(r['kg_auprc'])} & "
            f"{_signed(r['gain'])} & {ci} & {_signed(r.get('fp_gain'))} \\\\"
        )
    n_sig = verdict.get("n_sig")
    sig_txt = (f" $\\Delta_{{\\mathrm{{AUPRC}}}}$ CI excludes 0 on {n_sig}/{verdict['n_total']} "
               "detectors (image-clustered paired bootstrap)." if n_sig is not None else "")
    tail = (
        "\n\\bottomrule\n\\end{tabular}\n\\\\[2pt]\n"
        "{\\footnotesize $\\Delta_{\\mathrm{AUPRC}}>0$ on "
        f"{verdict['n_positive']}/{verdict['n_total']} detectors "
        f"(verdict: {verdict['verdict']})." + sig_txt +
        " $^{\\dagger}$The FP-suppression gain is at each method's own test operating "
        "point (TP-retention not exactly matched), so it overstates the effect and is "
        "context only; the AUPRC gain is the reliable, threshold-free measure.}\n\\end{table}\n"
    )
    return head + "\n".join(body) + tail


def render_md(rows, verdict: dict) -> str:
    lines = ["# E2 — detector-agnostic governance", "",
             "Same KG-evidence governance gate applied on each detector's boxes "
             "(same OIA-DDR split, retain-vs-suppress triage task). **PRIMARY metric "
             "= threshold-free AUPRC gain** (KG-gate − M0). The FP-suppression gain is "
             "shown for context only — it is sensitive to TP-retention mismatch on "
             "test and therefore overstates the effect.", "",
             "| Detector | M0 AUPRC | +Gov AUPRC | ΔAUPRC | 95% CI | sig | FP-supp Δ† | FP CI† | n_test |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        sig = "—" if r.get("gain_sig") is None else ("YES" if r["gain_sig"] else "no")
        lines.append(
            f"| {r['detector']} | {_fmt(r['m0_auprc'])} | {_fmt(r['kg_auprc'])} | "
            f"{_signed(r['gain'])} | {_ci(r)} | {sig} | {_signed(r.get('fp_gain'))} | "
            f"{_fpci(r)} | {r['n_test_boxes']} |")
    n_sig = verdict.get("n_sig")
    sig_line = (f" Of these, {n_sig}/{verdict['n_total']} have a 95% AUPRC-gain CI "
                f"excluding 0 (image-clustered)." if n_sig is not None else "")
    lines += ["",
              f"**Verdict: {verdict['verdict']}** — AUPRC gain Δ>0 on "
              f"{verdict['n_positive']}/{verdict['n_total']} detectors "
              f"(threshold: ≥{verdict['min_agnostic']} for detector-agnostic)."
              + sig_line, "",
              "> †FP-suppression gain is at each method's own test operating point "
              "(TP-retention NOT exactly matched, e.g. headline M0 TP 0.89 vs KG TP "
              "0.79), so it overstates the effect. The threshold-free AUPRC gain is the "
              "reliable measure. CI = image-clustered paired bootstrap.", ""]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="E2: aggregate detector-agnostic governance.")
    ap.add_argument("--bench", action="append", default=[],
                    help='"<detector name>=<path to fp_benchmark.json>". Repeatable.')
    ap.add_argument("--glob", default=None,
                    help="glob for *_fp_benchmark.json (name derived from filename).")
    ap.add_argument("--min_agnostic", type=int, default=2,
                    help="min #detectors with gain>0 to call governance detector-agnostic.")
    ap.add_argument("--out_parent", default="outputs/detcmp/_e2_aggregate")
    args = ap.parse_args()

    pairs = []
    for spec in args.bench:
        if "=" not in spec:
            print(f"[e2-agg] ERROR: --bench must be 'name=path', got: {spec}")
            return 2
        name, path = spec.split("=", 1)
        pairs.append((name.strip(), path.strip()))
    if args.glob:
        for p in sorted(_glob.glob(args.glob)):
            name = Path(p).name.replace("_fp_benchmark.json", "")
            pairs.append((name, p))
    # de-dup by path
    seen, uniq = set(), []
    for name, path in pairs:
        if path in seen:
            continue
        seen.add(path); uniq.append((name, path))
    if not uniq:
        print("[e2-agg] No benchmark JSONs given. Use --bench or --glob.")
        return 1

    rows = []
    for name, path in uniq:
        if not Path(path).exists():
            print(f"[e2-agg] WARN: missing {path} (skipped)")
            continue
        rows.append(load_bench(name, path))
    if not rows:
        print("[e2-agg] No readable benchmark JSONs.")
        return 1

    n_pos = sum(1 for r in rows if r["gain"] is not None and r["gain"] > 0)
    has_ci = any(r.get("gain_sig") is not None for r in rows)
    n_sig = sum(1 for r in rows if r.get("gain_sig")) if has_ci else None
    verdict = {
        "n_total": len(rows), "n_positive": n_pos, "min_agnostic": args.min_agnostic,
        "n_sig": n_sig,
        "verdict": "DETECTOR-AGNOSTIC (PASS)" if n_pos >= args.min_agnostic
        else "INSUFFICIENT (need more detectors with gain>0)",
    }

    out_dir = fresh_timestamped_dir(Path(args.out_parent), prefix="run")
    (out_dir / "e2_governance_summary.json").write_text(
        json.dumps({"verdict": verdict, "rows": rows}, indent=2), encoding="utf-8")
    (out_dir / "T11_e2_governance.tex").write_text(render_tex(rows, verdict), encoding="utf-8")
    (out_dir / "e2_detector_agnostic.md").write_text(render_md(rows, verdict), encoding="utf-8")

    print(f"[e2-agg] {len(rows)} detector(s):")
    for r in rows:
        sig = "" if r.get("gain_sig") is None else (
            f" CI={_ci(r)} sig={'YES' if r['gain_sig'] else 'no'}")
        print(f"[e2-agg]   {r['detector']:<26} AUPRC M0={_fmt(r['m0_auprc'])} "
              f"KG={_fmt(r['kg_auprc'])} dAUPRC={_signed(r['gain'])}{sig}")
    print(f"[e2-agg] gain>0 on {n_pos}/{len(rows)} -> {verdict['verdict']}"
          + (f"  (CI excludes 0 on {n_sig}/{len(rows)})" if n_sig is not None else ""))
    print(f"[e2-agg] wrote -> {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
