#!/usr/bin/env python
"""aggregate_detector_compare.py — collect the per-detector ``compare_results.json``
files produced by E1 (tools/train_detector_compare.py and, optionally,
tools/train_yolo_compare.py) and emit the FILLED model-level comparison:

  * aggregate_summary.json   — machine-readable, all rows + provenance
  * T10_model_level_results.tex — LaTeX table (real mAP@0.5 numbers, our split)
  * model_level_comparison.md   — human-readable summary

NO OVERWRITE BY CONSTRUCTION: every run writes into a brand-new timestamped dir
``outputs/detcmp/_aggregate/run_<ts>/`` (see tools/_safe_output.fresh_timestamped_dir),
so prior aggregations are never clobbered. The generated T10 .tex is written into
that run dir; copy it into journal/tables/ yourself when satisfied (so the journal
copy is never silently replaced).

This does NOT touch Mode 1 and reads ONLY comparison result files.

Usage (after E1 runs):
    python tools/aggregate_detector_compare.py \
        --results_root outputs/detcmp \
        --extra_glob "outputs/detcmp_yolo/*/compare_results.json"
"""
from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path

_here = Path(__file__).resolve().parent
_root = _here.parent
if str(_root) not in sys.path:
    sys.path.insert(0, str(_root))

from tools._safe_output import fresh_timestamped_dir  # noqa: E402

CLASS_ORDER = ["MA", "HE", "Hard_EX", "Soft_EX"]

# Display metadata per model_type. (display_name, year, type, anchor/recipe note)
META = {
    "fasterrcnn":     ("Faster R-CNN R50-FPN (ours)", 2017, "two-stage", "small-anchor (8..128)"),
    "fasterrcnn_v2":  ("Faster R-CNN R50-FPN-v2", 2021, "two-stage", "default"),
    "retinanet":      ("RetinaNet R50-FPN", 2017, "one-stage", "default"),
    "retinanet_v2":   ("RetinaNet R50-FPN-v2", 2021, "one-stage", "default"),
    "fcos":           ("FCOS R50-FPN", 2019, "anchor-free", "default"),
    "ssd300":         ("SSD300/VGG16", 2016, "one-stage", "default"),
    "yolov8s":        ("YOLOv8-s$^\\ast$", 2023, "one-stage", "yolo recipe"),
    "yolov8m":        ("YOLOv8-m$^\\ast$", 2023, "one-stage", "yolo recipe"),
    "rtdetr-l":       ("RT-DETR-L$^\\ast$", 2024, "transformer", "detr recipe"),
}


def _meta(model_type: str):
    key = model_type.lower().replace(".pt", "")
    if key in META:
        return META[key]
    return (model_type, None, "?", "?")


def _fmt(x) -> str:
    if x is None:
        return "[--]"
    try:
        if x != x:  # nan
            return "[--]"
        return f"{float(x):.3f}"
    except (TypeError, ValueError):
        return "[--]"


def load_results(paths) -> list:
    rows = []
    for p in paths:
        try:
            d = json.loads(Path(p).read_text(encoding="utf-8"))
        except Exception as exc:
            print(f"[agg] WARN: cannot read {p}: {exc}")
            continue
        mt = d.get("model_type", Path(p).parent.name)
        disp, year, typ, note = _meta(mt)
        valid = d.get("valid", {}) or {}
        test = d.get("test", {}) or {}
        rows.append({
            "model_type": mt, "display": disp, "year": year, "type": typ,
            "recipe": note, "source": str(p),
            "valid_mAP_50": valid.get("mAP_50", d.get("best_val_mAP_50")),
            "test_mAP_50": test.get("mAP_50"),
            "valid_per_class": valid.get("per_class_AP50", {}),
            "test_per_class": test.get("per_class_AP50", {}),
            "is_modern_ref": "$^\\ast$" in disp,
        })
    # sort: ours first, then by year then name
    rows.sort(key=lambda r: (0 if "ours" in r["display"] else 1,
                             r["year"] or 9999, r["display"]))
    return rows


def render_tex(rows) -> str:
    head = (
        "% T10 — FILLED model-level comparison (auto-generated by\n"
        "% tools/aggregate_detector_compare.py). Controlled: every row trained AND\n"
        "% evaluated on OUR OIA-DDR split with the SAME mAP@0.5 protocol\n"
        "% (tools/train_detector_compare.py). $^\\ast$ rows = modern ultralytics\n"
        "% reference (different training recipe; see note).\n"
        "\\begin{table}[t]\n\\centering\n"
        "\\caption{Model-level detector comparison on the \\emph{same} OIA-DDR "
        "detection split with an identical mAP$_{50}$ protocol. All detectors are "
        "stock architectures (no detector novelty claimed); the comparison "
        "positions our (also stock) detector. mAP$_{50}$ reported on valid and "
        "test.}\n"
        "\\label{tab:model_level_results}\n"
        "\\begin{tabular}{lcccc}\n\\toprule\n"
        "Detector (backbone) & Year & Type & mAP$_{50}$ valid & mAP$_{50}$ test \\\\\n"
        "\\midrule\n"
    )
    body = []
    for r in rows:
        year = r["year"] if r["year"] is not None else "--"
        body.append(
            f"{r['display']} & {year} & {r['type']} & "
            f"{_fmt(r['valid_mAP_50'])} & {_fmt(r['test_mAP_50'])} \\\\"
        )
    tail = (
        "\n\\bottomrule\n\\end{tabular}\n\\\\[2pt]\n"
        "{\\footnotesize All rows trained/evaluated under the identical mAP$_{50}$ "
        "protocol on our split (positioning, not a SOTA claim). $^\\ast$Modern "
        "ultralytics references (YOLOv8/RT-DETR) use a different training recipe "
        "(augmentation, input size) and are shown for context. Anchor/recipe per "
        "family is recorded in each checkpoint config.}\n\\end{table}\n"
    )
    return head + "\n".join(body) + tail


def _clean_display(disp: str) -> str:
    return disp.replace("$^\\ast$", "*")


def render_md(rows) -> str:
    lines = ["# Model-level comparison (E1, filled)", "",
             "All on the SAME OIA-DDR split, identical mAP@0.5 protocol. Stock "
             "detectors only; positioning (not a SOTA claim).", "",
             "| Detector | Year | Type | mAP50 valid | mAP50 test | recipe | source |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        year = r["year"] if r["year"] is not None else "--"
        disp = _clean_display(r["display"])
        src = r["source"]
        lines.append(
            f"| {disp} | {year} | {r['type']} | "
            f"{_fmt(r['valid_mAP_50'])} | {_fmt(r['test_mAP_50'])} | {r['recipe']} | "
            f"`{src}` |")
    # per-class valid block
    lines += ["", "## Per-class AP50 (valid)", "",
              "| Detector | " + " | ".join(CLASS_ORDER) + " |",
              "|---|" + "---|" * len(CLASS_ORDER)]
    for r in rows:
        pcs = r["valid_per_class"] or {}
        disp = _clean_display(r["display"])
        cells = " | ".join(_fmt(pcs.get(c)) for c in CLASS_ORDER)
        lines.append(f"| {disp} | {cells} |")
    lines += ["", f"Rows: {len(rows)}. Generated by aggregate_detector_compare.py."]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="Aggregate E1 detector results -> Table 10.")
    ap.add_argument("--results_root", default="outputs/detcmp",
                    help="dir whose */compare_results.json are collected.")
    ap.add_argument("--extra_glob", action="append", default=[],
                    help="additional glob(s) for compare_results.json (e.g. yolo). "
                         "Repeatable.")
    ap.add_argument("--out_parent", default="outputs/detcmp/_aggregate",
                    help="parent dir; a fresh timestamped run dir is created under it.")
    args = ap.parse_args()

    paths = sorted(glob.glob(str(Path(args.results_root) / "*" / "compare_results.json")))
    for g in args.extra_glob:
        paths += sorted(glob.glob(g))
    # de-dup, drop the aggregate dir itself
    paths = [p for p in dict.fromkeys(paths) if "_aggregate" not in p]
    if not paths:
        print(f"[agg] No compare_results.json found under {args.results_root} "
              f"(or extra globs). Run E1 first.")
        return 1

    rows = load_results(paths)
    out_dir = fresh_timestamped_dir(Path(args.out_parent), prefix="run")

    (out_dir / "aggregate_summary.json").write_text(
        json.dumps({"n_models": len(rows), "rows": rows}, indent=2), encoding="utf-8")
    (out_dir / "T10_model_level_results.tex").write_text(render_tex(rows), encoding="utf-8")
    (out_dir / "model_level_comparison.md").write_text(render_md(rows), encoding="utf-8")

    print(f"[agg] collected {len(rows)} model(s):")
    for r in rows:
        print(f"[agg]   {r['display']:<28} valid={_fmt(r['valid_mAP_50'])} "
              f"test={_fmt(r['test_mAP_50'])}")
    print(f"[agg] wrote -> {out_dir}")
    print(f"[agg]   aggregate_summary.json")
    print(f"[agg]   T10_model_level_results.tex  (copy into journal/tables/ when ready)")
    print(f"[agg]   model_level_comparison.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
