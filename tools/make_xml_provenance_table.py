#!/usr/bin/env python
"""make_xml_provenance_table.py — render S14 dari JSON audit provenans XML.

Membaca outputs/0506/xml_provenance/audit.json (dihasilkan oleh
tools/audit_xml_provenance.py) dan menulis _FINAL_Latex/tables/S14_xml_provenance.tex.
Tidak menghitung ulang apa pun.

Jalankan dari root repo:
  python tools/make_xml_provenance_table.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path


def _resolve(*candidates):
    for base in Path(__file__).resolve().parents:
        for rel in candidates:
            p = base / rel
            if p.exists():
                return p, base
    raise SystemExit("masukan tidak ditemukan: " + " atau ".join(candidates))


SRC, ROOT = _resolve("outputs/0506/xml_provenance/audit.json",
                     "results/xml_provenance/audit.json")
_TABLES = ROOT / "_FINAL_Latex/tables" if (ROOT / "_FINAL_Latex/tables").is_dir() else ROOT / "tables"
OUT = _TABLES / "S14_xml_provenance.tex"

ORDER = [("oiaddr", "OIA-DDR"), ("idrid", "IDRiD"), ("tjdr", "TJDR"), ("fgadr", "FGADR")]


def th(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    digest = hashlib.sha256(SRC.read_bytes()).hexdigest()[:16]

    rows = []
    for key, label in ORDER:
        v = d["cohorts"][key]
        deg = v["coordinate_issues"].get("kotak_degenerat", 0)
        rows.append(" & ".join([
            label,
            th(v["files_total"]),
            th(v["objects_total"]),
            th(v["distinct_boxes_total"]),
            th(deg),
            "none" if not v["split_id_overlap"] else str(v["split_id_overlap"]),
        ]) + r" \\")

    caption = (
        "Provenance of the annotation files, audited from the files themselves. Images "
        "counts the annotation files, boxes counts annotated objects, and distinct counts "
        "them after removing exact repeats within a file. Degenerate boxes have zero width "
        "or height, and split overlap counts image identifiers that appear in more than "
        "one split."
    )

    text = (
        "% Generated by tools/make_xml_provenance_table.py from frozen JSON; read-only audit.\n"
        "% Source: outputs/0506/xml_provenance/audit.json\n"
        f"% sha256[:16] = {digest}\n"
        "% Auditor: tools/audit_xml_provenance.py\n"
        "\\begin{table}[htbp]\n"
        "\\centering\n"
        "\\caption{" + caption + "}\n"
        "\\label{tab:xml_provenance}\n"
        "\\footnotesize\n"
        "\\setlength{\\tabcolsep}{4pt}\n"
        "\\begin{tabular}{lrrrrc}\n"
        "\\toprule\n"
        "Cohort & Images & Boxes & Distinct & Degenerate & Split \\\\\n"
        " & & & boxes & boxes & overlap \\\\\n"
        "\\midrule\n"
        + "\n".join(rows) + "\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
        "\\end{table}\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"ditulis {OUT}")
    print(f"sumber sha256[:16] = {digest}")


if __name__ == "__main__":
    main()
