def build_t13() -> str:
    d = json.loads(_first("_septem/scripts_optionB/clinical_cost_fusion.json",
                          "results/experiments/clinical_cost_fusion.json").read_text(encoding="utf-8"))
    sig = [d["signals"][k] for k in ("detector_score", "fused_three_pass", "kg_sdca")]

    def cell(s, grp):
        return f"${q(s['mean_' + grp])}\\pm{q(s['sd_' + grp + '_ddof0'])}$"

    def auroc(s):
        lo, hi = s["ci95"]
        return q(s["auroc"]) + (" (chance)" if lo <= 0.5 <= hi else "")

    unsafe = (f"UNSAFE (grade-shifting, higher cost) & SUPPRESS & {d['n_unsafe']:<4} & "
              + " & ".join(cell(s, "unsafe") for s in sig) + r" \\")
    close = (f"CLINICALLY-CLOSE (within-grade, lower cost) & RETAIN & {d['n_close']:<4} & "
             + " & ".join(cell(s, "close") for s in sig) + r" \\")
    sep = (r"\multicolumn{2}{l}{Separability (AUROC, higher vs.\ lower cost)} & & "
           + " & ".join(auroc(s) for s in sig) + r" \\")
    return "\n".join([
        "% T13 — generated by tools/make_core_tables.py; do not edit by hand.",
        "% Source: clinical_cost_fusion.json (OIA-DDR test, UNSAFE_MISMATCH against",
        "%   CLINICALLY_CLOSE_MISMATCH); SD is the population SD. The SDCA separation is",
        "%   partly definitional, because the lower-cost category is defined by a low prior cost.",
        r"\begin{table}[t]",
        r"\centering",
        "\\caption{Detector score, three-pass score mean and SDCA for grade-shifting (unsafe) and\n"
        "within-grade (clinically close) confusions on OIA-DDR test. AUROC measures how well\n"
        "each signal ranks the higher-cost confusions above the lower-cost ones, and 0.5 indicates\n"
        "no separation in either direction. The two categories follow the author-defined\n"
        "severity ordering of Section~\\ref{sec:kg}.}",
        r"\label{tab:clinical_cost}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{llcccc}",
        r"\toprule",
        r"Confusion type & Target & $n$ & Detector score (mean$\pm$sd) & Three-pass mean "
        r"(mean$\pm$sd) & KG SDCA (mean$\pm$sd) \\",
        r"\midrule",
        unsafe,
        close,
        r"\midrule",
        sep,
        r"\bottomrule",
        r"\end{tabular}}",
        r"\end{table}",
        "",
    ])


def main() -> int:
    TAB.mkdir(parents=True, exist_ok=True)
    for name, build in (("T11_governance_detector_agnostic.tex", build_t11),
                        ("T12_multisource_domain.tex", build_t12),
                        ("T13_clinical_cost_capability.tex", build_t13)):
        (TAB / name).write_text(build(), encoding="utf-8")
        print(f"[core] wrote {(TAB / name).relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
