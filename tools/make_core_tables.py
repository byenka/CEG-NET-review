#!/usr/bin/env python

from __future__ import annotations

import csv
import gzip
import json
import statistics
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TAB = ROOT / "_FINAL_Latex/tables"


def _first(*rels: str) -> Path:

    for r in rels:
        if (ROOT / r).exists():
            return ROOT / r
    raise SystemExit("input not found: " + " or ".join(rels))


def q(v: float, nd: int = 3) -> str:

    return str(Decimal(repr(float(v))).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))


def sq(v: float, nd: int = 3) -> str:
    return ("+" if v >= 0 else "-") + q(abs(v), nd)


# ── T11 ──────────────────────────────────────────────────────────────────────

DETECTORS = [  # (file stem, workspace folder, row name, per-ROI evidence)
    ("fasterrcnn", "detcmp_e2", "Faster R-CNN/FPN", "real ROI softmax"),
    ("fasterrcnn_v2", "detcmp_e2", "Faster R-CNN/FPN-v2", "real ROI softmax"),
    ("retinanet", "detcmp_e2", "RetinaNet", "real ROI softmax"),
    ("retinanet_v2", "detcmp_e2", "RetinaNet-v2", "real ROI softmax"),
    ("rtdetr_r18", "rtdetr_e2", "RT-DETR-R18", "real ROI softmax"),
    ("fcos", "detcmp_e2", "FCOS", "synthetic proxy"),
    ("yolo11s", "yolo_e2", "YOLO11s", "synthetic proxy"),
    ("yolov8s", "yolo_e2", "YOLOv8s", "synthetic proxy"),
]


def build_t11() -> str:
    rows = []
    for stem, folder, name, evid in DETECTORS:
        p = _first(f"outputs/0506/{folder}/{stem}_fp_benchmark.json",
                   f"results/tables_source/{stem}_fp_benchmark.json")
        d = json.loads(p.read_text(encoding="utf-8"))
        ap = {r["method"]: r["auprc"] for r in d["results"]}
        b = d["bootstrap_auprc"]["kg_minus_m0"]
        lo, hi = b["gain_ci95"]
        if b["sig"] != (lo > 0 or hi < 0):
            raise SystemExit(f"[T11] {stem}: sig flag disagrees with its interval")
        star = "^{*}" if b["sig"] else ""
        rows.append(f"{name:<22}& {evid:<16} & {q(ap['M0_score'])} & "
                    f"{q(ap['KG-gate-MLP (ours)'])} & ${sq(b['gain_point'])}$ & "
                    f"$[{sq(lo)},{sq(hi)}]{star}$ \\\\")
    return "\n".join([
        "% T11 — generated by tools/make_core_tables.py; do not edit by hand.",
        "% Source: outputs/0506/{detcmp_e2,rtdetr_e2,yolo_e2}/<det>_fp_benchmark.json",
        "%   (repository: results/tables_source/), light B4 configuration, gate seed 0,",
        "%   bootstrap_auprc.kg_minus_m0 with 2,000 image resamples.",
        r"\begin{table}[t]",
        r"\centering",
        "\\caption{Gating across eight detectors on OIA-DDR test with the light B4 gate formulation,\n"
        "refitted separately per detector (single-source agreement, geometric anatomy approximation,\n"
        "placeholder perturbation stability, no multi-source signals). $\\Delta$AUPRC is the gain of\n"
        "the gate over the detector score $M_0$, with a 95\\% image-clustered paired-bootstrap "
        "interval. The eight detectors are trained independently of the primary detector, so "
        "their $M_0$ values differ from Table~\\ref{tab:fp_benchmark}.}",
        r"\label{tab:governance_final}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{llcccc}",
        r"\toprule",
        r"Detector & per-ROI evid. & $M_0$ & Gate & $\Delta$AUPRC & 95\% CI($\Delta$) \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}}",
        r"\\[2pt]",
        r"{\footnotesize $^{*}$Interval excludes zero (2{,}000 resamples).}",
        r"\end{table}",
        "",
    ])


# ── T12 ──────────────────────────────────────────────────────────────────────

EVIDENCE = {  # cohort name -> (workspace CSV, repository gzipped CSV)
    "OIA-DDR": ("outputs/0506/evsds_v2sec/oiaddr/test/governance_features_test.csv",
                "results/evidence/oiaddr_test_evidence.csv.gz"),
    "IDRiD": ("outputs/0506/evsds_pss/idrid/test/governance_features_test.csv",
              "results/evidence/idrid_test_evidence.csv.gz"),
    "TJDR": ("outputs/0506/evsds_pss/tjdr/test/governance_features_test.csv",
             "results/evidence/tjdr_test_evidence.csv.gz"),
    "FGADR": ("outputs/0506/evsds_pss/fgadr/train/governance_features_train.csv",
              "results/evidence/fgadr_train_evidence.csv.gz"),
}
T12_LABEL = {"OIA-DDR": "OIA-DDR (in-domain)", "IDRiD": "IDRiD (zero-shot)",
             "TJDR": "TJDR (zero-shot)", "FGADR": "FGADR (zero-shot)"}
FUSION_KEY = {"OIA-DDR": "oiaddr", "IDRiD": "idrid", "TJDR": "tjdr", "FGADR": "fgadr"}


def pss_coverage(cohort: str) -> float:
    p = _first(*EVIDENCE[cohort])
    opener = gzip.open if p.suffix == ".gz" else open
    n = live = 0
    with opener(p, "rt", newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            n += 1
            live += r["ev_pss_status"] == "implemented"
    return live / n


def seed_gain(a: list, b: list) -> tuple:
    d = [x - y for x, y in zip(a, b)]
    return statistics.mean(d), statistics.stdev(d), sum(x > 0 for x in d)


def build_t12() -> str:
    dom = json.loads(_first("outputs/0506/evsds_pss/domain_shift_5seed.json",
                            "results/tables_source/domain_shift_5seed.json").read_text(encoding="utf-8"))
    fus = json.loads(_first("_septem/finalization_five_priorities/fusion_external.json",
                            "results/finalization/fusion_external.json").read_text(encoding="utf-8"))
    step6 = json.loads(_first("_LGOVNET_NEW_SEP/results/step6_fgadr_three_pass.json",
                              "results/conditional_coverage/step6_fgadr_three_pass.json")
                       .read_text(encoding="utf-8"))
    assert step6["verdict"].startswith("C1"), "step 6 did not complete its controls"
    by_fus = {c["key"]: c for c in fus["cohorts"]}
    rows = []
    for c in dom["cohorts"]:
        name = c["name"]
        f = by_fus[FUSION_KEY[name]]
        m0, b4, b6 = c["m0_auprc"], c["b4_auprc_mean"], c["b6_auprc_mean"]
        # The domain-shift file uses the trapezoid AUPRC and the fusion file average
        # precision; they differ by at most 1.5e-4 and must agree at the printed precision.
        assert q(f["m0_ap"]) == q(m0) and q(f["gates"]["full_gate"]["ap_mean"]) == q(b6), name
        if name == "FGADR":  # three-pass fusion from the locked step 6
            g = step6["fgadr_three_pass"]["B_fusion_input_gate"]
            fused = step6["fgadr_three_pass"]["A_fusion_auprc"]
        else:
            g, fused = f["gates"]["gate_fused"], f["fused_ap"]
        fe, fe_sd, fe_gain = g["ap_mean"], g["ap_sd"], g["gain_vs_fused_mean"]
        pos, neg = g["n_ci_above_0"], g["n_ci_below_0"]
        m6, s6, n6 = seed_gain(c["b6_auprc_per_seed"], [m0] * 5)
        m64, s64, n64 = seed_gain(c["b6_auprc_per_seed"], c["b4_auprc_per_seed"])
        top = max(m0, fused, b4, b6, fe)  # bold marks the best AUPRC in the row

        def b(v):
            return rf"\textbf{{{v:.3f}}}" if v == top else f"{v:.3f}"
        fe_txt = (rf"$\mathbf{{{fe:.3f}}}\pm{fe_sd:.3f}$" if fe == top
                  else rf"${fe:.3f}\pm{fe_sd:.3f}$")
        if name == "IDRiD":  # the in-domain row is set apart from the zero-shot rows
            rows.append(r"\midrule")
        rows.append(
            f"{T12_LABEL[name]:<19} & {pss_coverage(name):.2f} & {b(m0)} & {b(fused)} & {b(b4)} & "
            f"{b(b6)} & {fe_txt} & ${m6:+.3f}\\pm{s6:.3f}$ ({n6}/5) & "
            f"${m64:+.3f}\\pm{s64:.3f}$ ({n64}/5) & ${fe_gain:+.3f}$ ({pos}/5; {neg}/5) \\\\")
        if name == "TJDR":
            assert (pos, neg) == (0, 1), "the TJDR footnote no longer matches the intervals"
    return "\n".join([
        "% T12 — generated by tools/make_core_tables.py; do not edit by hand.",
        "% Source: domain_shift_5seed.json (M0, B4, B6 per seed; gains are mean and sample SD",
        "%   of per-seed differences), fusion_external.json (F, F+E, (F+E)-F; FGADR from",
        "%   step6_fgadr_three_pass.json) and the evidence CSVs (PSS cov. = share of",
        "%   detections with ev_pss_status 'implemented'). M0, B4 and B6 use the trapezoid",
        "%   AUPRC of the domain-shift run, F and F+E average precision; M0 and B6 agree",
        "%   between the two estimators to the printed three decimals.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Ranking in domain and under domain shift. The gate is fitted on OIA-DDR "
        r"validation and applied unchanged to the three external datasets. Score fusion ($F$) "
        r"averages the detector scores of the three passes the gate already consumes, and the "
        r"fusion-input gate ($F{+}E$) reads that mean in place of the raw score. Gate AUPRC "
        r"values are five-seed means, gains are mean $\pm$ SD with the number of seeds showing "
        r"a positive gain in parentheses, and the last column gives the mean $(F{+}E)-F$ "
        r"difference with the number of seed intervals (2{,}000 paired image resamples) wholly "
        r"above and below zero. PSS cov.\ is the fraction of detections with a measured "
        r"perturbation-stability value, and Supplementary~S2 gives the per-seed values. Best "
        r"AUPRC per row in bold.}",
        r"\label{tab:multisource_domain}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{lccccccccc}",
        r"\toprule",
        r" & & \multicolumn{5}{c}{AUPRC$\uparrow$} & \multicolumn{2}{c}{Gain (mean$\pm$SD)} "
        r"& \multicolumn{1}{c}{$(F{+}E)-F$} \\",
        r"\cmidrule(lr){3-7}\cmidrule(lr){8-9}\cmidrule(lr){10-10}",
        r"Domain & PSS cov. & $M_0$ & $F$ & KG-gate (B4) & Full gate (B6) & $F{+}E$ & "
        r"B6 $-$ $M_0$ & B6 $-$ B4 & mean (CI $>0$; $<0$) \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}}",
        r"\par\smallskip{\footnotesize For TJDR, one negative interval and four containing zero "
        r"accompany five negative point estimates of $(F{+}E)-F$.}",
        r"\end{table}",
        "",
    ])


