#!/usr/bin/env python
"""make_ensemble_bound_table.py — render S17 dari JSON beku ensemble multi-detektor.

Membaca hasil _LGOVNET_NEW_SEP/results/ensemble_external.json (atau salinan paket) dan menulis
_FINAL_Latex/tables/S17_ensemble_bound.tex. Tidak menghitung ulang apa pun.

Jalankan dari root repo:
  python tools/make_ensemble_bound_table.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path


def _resolve(*candidates):
    for base in Path(__file__).resolve().parents:
        for rel in candidates:
            p = base / rel
            if p.exists():
                return p, base
    raise SystemExit("masukan tidak ditemukan: " + " atau ".join(candidates))


SRC, ROOT = _resolve("_LGOVNET_NEW_SEP/results/ensemble_external.json",
                     "results/ensemble/ensemble_external.json")
_TABLES = ROOT / "_FINAL_Latex/tables" if (ROOT / "_FINAL_Latex/tables").is_dir() else ROOT / "tables"
OUT = _TABLES / "S17_ensemble_bound.tex"

ORDER = ["OIA-DDR test", "IDRiD", "TJDR", "FGADR"]
KEY_S = "S (detector score)"
KEY_E5 = "E5 (five detectors)"
KEY_E6 = "E6 (six detectors)"
KEY_G = "S+E (full gate)"


def f4(x):
    return f"{x:.4f}"


def sg3(x):
    return f"$+{x:.3f}$" if x >= 0 else f"$-{abs(x):.3f}$"


def th(n):
    return f"{n:,}".replace(",", "{,}")


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    dig = hashlib.sha256(SRC.read_bytes()).hexdigest()[:16]

    rows = []
    for c in ORDER:
        e = d["cohorts"][c]
        m = e["methods"]
        pv = e.get("paired_vs_E6")
        if isinstance(pv, dict) and KEY_G in pv and pv[KEY_G]:
            p = pv[KEY_G]
            lo, hi = p["ci95"]
            delta = (f"$-{abs(p['delta']):.4f}$" if p["delta"] < 0 else f"$+{p['delta']:.4f}$")
            ci = (f"$[-{abs(lo):.4f}, -{abs(hi):.4f}]$" if hi < 0
                  else f"$[{lo:+.4f}, {hi:+.4f}]$")
        else:
            delta = f"$-{abs(m[KEY_G]['auprc'] - m[KEY_E6]['auprc']):.4f}$"
            ci = "not resampled"
        aus = [m[KEY_S]["auprc"], m[KEY_E5]["auprc"], m[KEY_E6]["auprc"], m[KEY_G]["auprc"]]
        top = max(aus)  # bold marks the best AUPRC in the row, whichever method holds it
        def bb(v, _t=top):
            return (r"\textbf{" + f4(v) + "}") if v == _t else f4(v)
        rows.append(" & ".join([
            c, th(e["n"]),
            bb(aus[0]), bb(aus[1]), bb(aus[2]),
            bb(aus[3]), delta, ci,
            sg3(m[KEY_G]["conformal_gap"]), sg3(m[KEY_E6]["conformal_gap"]),
        ]) + r" \\")

    caption = (
        "Multi-detector ensembling. E5 averages the five comparison detectors and E6 adds the "
        "primary detector. $\\Delta$ is the paired AUPRC difference between the full gate and E6 "
        "with an image-clustered 95\\% interval, and the last two columns repeat the conformal "
        "coverage gap. Best AUPRC per row in bold."
    )

    text = (
        "% Generated by tools/make_ensemble_bound_table.py from frozen JSON; no refitting.\n"
        "% Source: _LGOVNET_NEW_SEP/results/ensemble_external.json\n"
        f"% sha256[:16] = {dig}\n"
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption{" + caption + "}\n"
        "\\label{tab:ensemble_bound}\n\\footnotesize\n"
        "\\setlength{\\tabcolsep}{3pt}\n\\resizebox{\\textwidth}{!}{%\n"
        "\\begin{tabular}{lrrrrrrcrr}\n\\toprule\n"
        "\\multirow{2}{*}{Cohort} & \\multirow{2}{*}{$n$} & \\multicolumn{4}{c}{AUPRC$\\uparrow$} "
        "& \\multicolumn{2}{c}{Gate $-$ E6} & \\multicolumn{2}{c}{Coverage gap} \\\\\n"
        "\\cmidrule(lr){3-6}\\cmidrule(lr){7-8}\\cmidrule(lr){9-10}\n"
        " & & $S$ & E5 & E6 & gate & $\\Delta$ & 95\\% CI & gate & E6 \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}}\n\\end{table}\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"ditulis {OUT}")
    print(f"sumber sha256[:16] = {dig}")


if __name__ == "__main__":
    main()
