#!/usr/bin/env python
"""make_honest_calibration_table.py — render T18 from the frozen step-2 JSON.

The table was previously written by hand, which let it fall behind its source.
It reads point estimates only: the two signed coverage gaps, the mean of the two
absolute gaps, the two risk-coverage areas and their absolute difference. No
confidence interval is printed, so the interval fields of the JSON are not used.

Run from the repository root:
    python tools/make_honest_calibration_table.py
"""
from __future__ import annotations

import hashlib
import json
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "_LGOVNET_NEW_SEP/results/step2_honest_calibration.json"
LOCK = "_LGOVNET_NEW_SEP/PROTOCOL_LOCK_step2_honest_calibration.md"
OUT = ROOT / "_FINAL_Latex/experiments/honest_calibration/T18_honest_calibration.tex"

ROWS = [
    ("S (detector score)", r"Detector score ($M_0$)", ""),
    ("M (top1-top2 margin)", r"Top-1$-$top-2 margin", ""),
    ("EL (evidence, linear)", r"Evidence, linear", ""),
    ("KG gate", r"Knowledge-graph gate", r"$^{\dagger}$"),
    ("FG (full gate)", r"Full gate, CEG-Net", r"$^{\dagger}$"),
]
COHORTS = ["OIA-DDR test", "IDRiD", "TJDR", "FGADR"]


def q(v: float, nd: int = 4) -> str:
    return str(Decimal(repr(float(v))).quantize(Decimal(1).scaleb(-nd),
                                                rounding=ROUND_HALF_UP))


def signed(v: float) -> str:
    return f"${float(v):+.4f}$"


def main() -> int:
    if not SRC.is_file():
        raise SystemExit(f"[honest] missing {SRC}")
    rep = json.loads(SRC.read_text(encoding="utf-8"))
    sha = hashlib.sha256(SRC.read_bytes()).hexdigest()[:16]
    h1 = rep["configs"]["H1"]["methods"]
    h1p = rep["configs"]["H1p"]["methods"]

    body = []
    for key, label, mark in ROWS:
        for i, coh in enumerate(COHORTS):
            a, b = h1[key][coh], h1p[key][coh]
            mean_abs = (abs(a["gap"]) + abs(b["gap"])) / 2.0
            d_aurc = abs(a["aurc"] - b["aurc"])
            head = label + mark if i == 0 else ""
            body.append(
                f"{head} & {coh} & {signed(a['gap'])} & {signed(b['gap'])} & "
                f"{q(mean_abs)} & {q(a['aurc'])} & {q(b['aurc'])} & {q(d_aurc)} " + chr(92) * 2)
        if key != ROWS[-1][0]:
            body.append(r"\midrule")

    rev = h1["M (top1-top2 margin)"]["TJDR"]["gap"], h1p["M (top1-top2 margin)"]["TJDR"]["gap"]
    understate = (abs(rev[0]) + abs(rev[1])) / 2.0 - abs((rev[0] + rev[1]) / 2.0)

    tex = "\n".join([
        "% Generated by tools/make_honest_calibration_table.py from the frozen step-2 JSON.",
        f"% Source: {SRC.relative_to(ROOT).as_posix()}",
        f"% sha256[:16] = {sha}",
        f"% Protocol locked before the run: {LOCK}",
        "% Point estimates only; the table prints no confidence interval.",
        "% Guarantee note: image-disjoint split with a finite-sample quantile correction; "
        "NOT an exact conformal guarantee, because detections within one image are dependent",
        "% NOT included by main.tex. To use it: "
        r"\input{T18_honest_calibration}",
        r"\begin{table}[t]",
        r"\centering",
        (r"\caption{Operating-point transfer under image-disjoint calibration. OIA-DDR validation is "
         r"split by image into two folds. The gate is fitted on one and every method, fitted or "
         r"not, has its threshold calibrated on the other, which is then frozen and applied "
         r"unchanged to all four cohorts. Both split directions are reported separately: H1 fits "
         r"on fold A and calibrates on fold B, H1$'$ swaps them. The coverage gap is the "
         r"delivered minus the intended 0.80 true-positive retention, and $\overline{|g|}$ is "
         r"the mean of the two absolute gaps, not the absolute value of the mean. Learned rows "
         r"average five gate seeds. This is an image-disjoint split with a finite-sample quantile "
         r"correction, not an exact conformal guarantee: detections inside one image remain "
         r"dependent.}"),
        r"\label{tab:honest_calibration}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{llrrrrrr}",
        r"\toprule",
        r" & & \multicolumn{3}{c}{Coverage gap} & \multicolumn{3}{c}{AURC (lower is better)} \\",
        r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}",
        r"Method & Cohort & H1 & H1$'$ & $\overline{|g|}$ & H1 & H1$'$ & $|\Delta|$ \\",
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}}",
        (r"\par\smallskip{\footnotesize $^{\dagger}$Mean over the five gate-initialization seeds. "
         r"Both gates hold a smaller absolute coverage gap and a lower AURC than the detector "
         r"score in every cohort and in both split directions. The only sign reversal between "
         r"directions is the margin on TJDR, " + signed(rev[0]) + " against " + signed(rev[1]) +
         r", which averaging would understate by " + q(understate) +
         r". It concerns a comparator and not the gates.}"),
        r"\end{table}",
        "",
    ])
    OUT.write_text(tex, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"source sha256[:16] = {sha}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
