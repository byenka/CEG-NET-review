#!/usr/bin/env python
"""make_certificate_verification_table.py — render S13 dari JSON verifikasi sertifikat.

Membaca outputs/0506/certificates/verification.json (dihasilkan oleh
tools/verify_certificates.py) dan menulis _FINAL_Latex/tables/S13_certificate_verification.tex.
Tidak menghitung ulang apa pun.

Jalankan dari root repo:
  python tools/make_certificate_verification_table.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

def _resolve(*candidates):
    """Cari berkas masukan di beberapa tata letak: workspace riset dan paket unggah."""
    for base in Path(__file__).resolve().parents:
        for rel in candidates:
            p = base / rel
            if p.exists():
                return p, base
    raise SystemExit("masukan tidak ditemukan: " + " atau ".join(candidates))


SRC, ROOT = _resolve("outputs/0506/certificates/verification.json",
                     "results/certificates/verification.json")
_TABLES = ROOT / "_FINAL_Latex/tables" if (ROOT / "_FINAL_Latex/tables").is_dir() else ROOT / "tables"
OUT = _TABLES / "S13_certificate_verification.tex"

ORDER = [("oiaddr", "OIA-DDR test"), ("idrid", "IDRiD"), ("tjdr", "TJDR"), ("fgadr", "FGADR")]


def thousands(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    digest = hashlib.sha256(SRC.read_bytes()).hexdigest()[:16]
    c1 = d["checks"]["C1_determinism"]["per_cohort"]

    rows = []
    for key, label in ORDER:
        v = d["per_cohort"][key]
        rows.append(" & ".join([
            label,
            thousands(v["n"]),
            "yes" if c1[key]["identical"] else "no",
            f"{v['C2_decision_tier_match'] / v['n'] * 100:.1f}",
            f"{v['C3_sdca_match'] / v['n'] * 100:.1f}",
            f"{v['C5_prior_fields_ranker_free'] / v['n'] * 100:.1f}",
            f"{v['C4_rate'] * 100:.2f}",
        ]) + r" \\")

    total_n = sum(d["per_cohort"][k]["n"] for k, _ in ORDER)

    caption = (
        "Technical verification of the per-detection audit certificate. Re-emission "
        "compares the SHA-256 of every re-generated file, and decision and tier "
        "reconstruction, prior consistency and ranker-free fields are recomputed from "
        "the certificate fields alone. The last column reports how often the emitted "
        "label differs from the per-ROI argmax, which the certificate discloses."
    )

    text = (
        "% Generated by tools/make_certificate_verification_table.py from frozen JSON;\n"
        "% no model fitting. Source: outputs/0506/certificates/verification.json\n"
        f"% sha256[:16] = {digest}\n"
        "% Emitter: tools/emit_certificates.py   Verifier: tools/verify_certificates.py\n"
        "\\begin{table}[htbp]\n"
        "\\centering\n"
        "\\caption{" + caption + "}\n"
        "\\label{tab:certificate_verification}\n"
        "\\footnotesize\n"
        "\\setlength{\\tabcolsep}{4pt}\n"
        "\\resizebox{\\textwidth}{!}{%\n"
        "\\begin{tabular}{lrcrrrr}\n"
        "\\toprule\n"
        "Cohort & $n$ & Re-emission & Decision and tier & Prior value & Ranker-free "
        "& Emitted label \\\\\n"
        " & & identical & reconstructed (\\%) & consistent (\\%) & fields (\\%) "
        "& $\\neq$ argmax (\\%) \\\\\n"
        "\\midrule\n"
        + "\n".join(rows) + "\n"
        "\\bottomrule\n"
        "\\end{tabular}}\n"
        "\\end{table}\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"ditulis {OUT}")
    print(f"sumber sha256[:16] = {digest}   total n = {total_n}")


if __name__ == "__main__":
    main()
