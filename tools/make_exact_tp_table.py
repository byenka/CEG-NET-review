#!/usr/bin/env python
"""make_exact_tp_table.py — render S23 (exact-true-positive sensitivity) from frozen JSON.

Source: the tp_exact task of step3_exact_tp_and_gap_ci.json, produced under
PROTOCOL_LOCK_step3_exact_tp_and_gap_ci.md. Nothing is recomputed.

Run from the repository root:
  python tools/make_exact_tp_table.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path


def _resolve(*candidates):
    for base in Path(__file__).resolve().parents:
        for rel in candidates:
            p = base / rel
            if p.exists():
                return p, base
    raise SystemExit("masukan tidak ditemukan: " + " atau ".join(candidates))


SRC, ROOT = _resolve("_LGOVNET_NEW_SEP/results/step3_exact_tp_and_gap_ci.json",
                     "results/conditional_coverage/step3_exact_tp_and_gap_ci.json")
_TABLES = ROOT / "_FINAL_Latex/tables" if (ROOT / "_FINAL_Latex/tables").is_dir() else ROOT / "tables"

COHORTS = ["OIA-DDR test", "IDRiD", "TJDR", "FGADR"]
M0 = "M0_score"
METHODS = [
    (M0, r"Detector score ($M_0$)"),
    ("KG-gate-MLP (ours)", "Knowledge-graph gate"),
    ("KG-gate+SDS+corrob (B6)", "Full gate, CEG-Net"),
]


def sg3(x: float) -> str:
    return f"$+{x:.3f}$" if x >= 0 else f"$-{abs(x):.3f}$"


def ci(rec: dict) -> str:
    # four decimals: at three, the TJDR upper bound of +0.0003 would print as +0.000 and read as zero
    lo, hi = rec["ci95"]
    return f"${rec['point']:+.4f}$ $[{lo:+.4f}, {hi:+.4f}]$"


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    dig = hashlib.sha256(SRC.read_bytes()).hexdigest()[:16]
    t = d["tasks"]["tp_exact"]
    rows = []
    for c in COHORTS:
        r = t["cohorts"][c]
        best = max(r["auprc"][k] for k, _ in METHODS)  # bold marks the best AUPRC in the cohort
        for i, (key, label) in enumerate(METHODS):
            head = (f"\\multirow{{3}}{{*}}{{{c}}} " if i == 0 else "") + "&"
            ap = f"{r['auprc'][key]:.4f}"
            if r["auprc"][key] == best:
                ap = r"\textbf{" + ap + "}"
            if key == M0:
                adv, gain, seeds = "---", "---", "---"
            else:
                adv = ci(r["abs_gap_advantage"][key])
                g = r["auprc_gain_per_seed"][key]
                gain = f"${g['mean']:+.4f}\\pm{g['sd']:.4f}$"
                seeds = f"{g['n_ci_above_0']}/5; {g['n_ci_below_0']}/5"
            rows.append(f"{head} {label} & {sg3(r['gap'][key])} & {adv} & {ap} & {gain} & {seeds} " + r"\\")
        rows.append(r"\midrule" if c != COHORTS[-1] else "")
    body = "\n".join(x for x in rows if x)

    nval = t["n_valid"], t["n_valid_positive"]
    caption = (
        "Exact-true-positive sensitivity: the RETAIN target is replaced by the exact true positive, and the gate "
        "and its threshold are refitted on OIA-DDR validation. $|g_{\\mathrm{gate}}|-|g_{\\mathrm{raw}}|$ is the "
        "change in absolute coverage gap with an image-clustered paired 95\\% interval, and the last two columns "
        "give the AUPRC gain over $M_0$ and the number of seed intervals above and below zero. "
        "Best AUPRC per cohort in bold."
    )
    note = (
        f"The gate is fitted on {nval[0]:,} OIA-DDR validation detections, {nval[1]:,} of them exact true "
        "positives. Positives per cohort: "
        + ", ".join(f"{c} {t['cohorts'][c]['n_positive']:,}" for c in COHORTS)
        + ". The gain columns are reported as measured, including the negative values."
    )
    text = (
        "% Generated by tools/make_exact_tp_table.py from frozen JSON; no refitting.\n"
        "% Source: _LGOVNET_NEW_SEP/results/step3_exact_tp_and_gap_ci.json (task tp_exact)\n"
        f"% sha256[:16] = {dig}\n"
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption{" + caption + "}\n"
        "\\label{tab:exact_tp}\n\\footnotesize\n"
        "\\setlength{\\tabcolsep}{4pt}\n\\resizebox{\\textwidth}{!}{%\n"
        "\\begin{tabular}{llccccc}\n\\toprule\n"
        "Cohort & Method & Gap & $|g_{\\mathrm{gate}}|-|g_{\\mathrm{raw}}|$ (95\\% CI) & AUPRC$\\uparrow$ "
        "& $\\Delta$AUPRC vs.\\ $M_0$ & Seeds CI $>0$; $<0$ \\\\\n"
        "\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}}\n"
        f"\\par\\smallskip{{\\footnotesize {note}}}\n"
        "\\end{table}\n"
    )
    _TABLES.mkdir(parents=True, exist_ok=True)
    (_TABLES / "S23_exact_tp_sensitivity.tex").write_text(text, encoding="utf-8")
    print(f"ditulis {_TABLES / 'S23_exact_tp_sensitivity.tex'}")
    print(f"sumber sha256[:16] = {dig}")


if __name__ == "__main__":
    main()
