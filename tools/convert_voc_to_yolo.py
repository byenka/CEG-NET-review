#!/usr/bin/env python
"""convert_voc_to_yolo.py — convert OUR OIA-DDR Pascal-VOC XML annotations into
YOLO/ultralytics format for the OPTIONAL modern comparators (YOLOv8 / RT-DETR).

Fairness contract (critical): this reuses ``DRDetectionDataset`` directly, so the
images, the raw->canonical class mapping (``map_raw_to_kg``), and the box-validity
filtering are BYTE-FOR-BYTE the same samples the torchvision comparison detectors
(E1) train on. No re-implementation of parsing => no protocol drift => the YOLO
comparison stays on the SAME split with the SAME labels.

Class id mapping (YOLO is 0-indexed; torchvision was 1-indexed):
    0 = MA      1 = HE      2 = Hard_EX     3 = Soft_EX
(YOLO_id = torchvision_label - 1.)

Output layout (ultralytics convention; ``valid`` -> ``val``):
    <out>/images/{train,val,test}/<stem>.jpg
    <out>/labels/{train,val,test}/<stem>.txt   # "cls cx cy w h" normalised [0,1]
    <out>/data.yaml

NEVER overwrites a previous conversion: refuses if <out> already has data.yaml
unless --overwrite is passed (see tools/_safe_output.py).

Usage (server):
    python tools/convert_voc_to_yolo.py \
        --data_root data/oiaddr --out data/oiaddr_yolo --link
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

_here = Path(__file__).resolve().parent
_root = _here.parent
if str(_root) not in sys.path:
    sys.path.insert(0, str(_root))

from tools._safe_output import guard_output_dir  # noqa: E402
from src.data.coco_adapter import DRDetectionDataset, LABEL_NAMES  # noqa: E402

# ultralytics uses "val"; our splits are train/valid/test.
SPLIT_MAP = {"train": "train", "valid": "val", "test": "test"}


def _link_or_copy(src: Path, dst: Path, link: bool) -> None:
    if dst.exists():
        return
    if link:
        try:
            dst.symlink_to(src)
            return
        except OSError:
            pass  # fall back to copy (e.g. Windows without privilege)
    shutil.copy2(src, dst)


def convert_split(ds: DRDetectionDataset, out: Path, yolo_split: str, link: bool) -> dict:
    from PIL import Image as PILImage

    img_out = out / "images" / yolo_split
    lbl_out = out / "labels" / yolo_split
    img_out.mkdir(parents=True, exist_ok=True)
    lbl_out.mkdir(parents=True, exist_ok=True)

    n_imgs, n_boxes, n_clip = 0, 0, 0
    per_class = {name: 0 for name in LABEL_NAMES}

    for s in ds._samples:  # same filtered samples as torchvision E1
        stem = s["stem"]
        img_path = Path(s["img_path"])
        with PILImage.open(img_path) as im:
            W, H = im.size
        if W <= 0 or H <= 0:
            continue

        lines = []
        for (x1, y1, x2, y2), lbl in zip(s["boxes"], s["labels"]):
            # clip to image bounds (defensive; boxes already validated positive-area)
            x1c, y1c = max(0, min(x1, W)), max(0, min(y1, H))
            x2c, y2c = max(0, min(x2, W)), max(0, min(y2, H))
            if x2c <= x1c or y2c <= y1c:
                continue
            if (x1c, y1c, x2c, y2c) != (x1, y1, x2, y2):
                n_clip += 1
            cx = (x1c + x2c) / 2.0 / W
            cy = (y1c + y2c) / 2.0 / H
            bw = (x2c - x1c) / W
            bh = (y2c - y1c) / H
            cls0 = int(lbl) - 1  # 1-indexed -> 0-indexed YOLO class
            lines.append(f"{cls0} {cx:.6f} {cy:.6f} {bw:.6f} {bh:.6f}")
            per_class[LABEL_NAMES[cls0]] += 1
            n_boxes += 1

        if not lines:
            continue
        # image (preserve original extension)
        _link_or_copy(img_path, img_out / img_path.name, link)
        (lbl_out / f"{stem}.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
        n_imgs += 1

    return {"images": n_imgs, "boxes": n_boxes, "clipped_boxes": n_clip,
            "per_class": per_class}


def write_data_yaml(out: Path) -> Path:
    names_block = "\n".join(f"  {i}: {name}" for i, name in enumerate(LABEL_NAMES))
    yaml = (
        "# Auto-generated by tools/convert_voc_to_yolo.py — OIA-DDR, SAME split as\n"
        "# the torchvision comparison detectors (E1). Classes match map_raw_to_kg.\n"
        f"path: {out.resolve().as_posix()}\n"
        "train: images/train\n"
        "val: images/val\n"
        "test: images/test\n"
        f"nc: {len(LABEL_NAMES)}\n"
        "names:\n"
        f"{names_block}\n"
    )
    p = out / "data.yaml"
    p.write_text(yaml, encoding="utf-8")
    return p


def main() -> int:
    ap = argparse.ArgumentParser(description="VOC-XML -> YOLO converter (OIA-DDR).")
    ap.add_argument("--data_root", default="data/oiaddr")
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--link", action="store_true",
                    help="symlink images instead of copying (Linux server).")
    ap.add_argument("--max_images", type=int, default=None,
                    help="cap per split (smoke test only).")
    ap.add_argument("--overwrite", action="store_true",
                    help="allow replacing a previous conversion at --out.")
    args = ap.parse_args()

    out = guard_output_dir(args.out, overwrite=args.overwrite, tag="[voc2yolo]")
    print(f"[voc2yolo] data_root={args.data_root}  out={out}  link={args.link}")

    totals = {}
    for raw_split, yolo_split in SPLIT_MAP.items():
        ds = DRDetectionDataset(split=raw_split, data_root=str(args.data_root),
                                max_images=args.max_images)
        stats = convert_split(ds, out, yolo_split, args.link)
        totals[yolo_split] = stats
        print(f"[voc2yolo] {raw_split:>5} -> {yolo_split:<4}  "
              f"images={stats['images']}  boxes={stats['boxes']}  "
              f"clipped={stats['clipped_boxes']}  per_class={stats['per_class']}")

    yaml_path = write_data_yaml(out)
    print(f"[voc2yolo] wrote {yaml_path}")
    print("[voc2yolo] DONE. Class ids: " +
          ", ".join(f"{i}={n}" for i, n in enumerate(LABEL_NAMES)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
