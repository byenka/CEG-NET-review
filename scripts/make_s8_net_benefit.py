"""make_s8_net_benefit.py — tabel suplemen S8 dari net_benefit_isotonic_check.json + net_benefit_bootstrap.json.

Isi: manfaat bersih (decision curve analysis, Vickers dan Elkin) pada tugas triase
retain-versus-suppress, menjawab keberatan "nilai klinisnya belum ditunjukkan" tanpa studi pembaca.

DUA HAL YANG WAJIB DIJAGA DI SINI.
1. JANGAN memakai net_benefit.json (v1). Ambangnya kuantil sehingga fraksi retensi terpaku pada
   p_t dan NB terkunci <= p_t; kemenangan retain-semua pada p_t <= 0.20 di sana DIPAKSA aritmetika.
   Tabel ini memakai aturan baku p_hat >= p_t atas probabilitas TERKALIBRASI.
2. Setiap sistem diberi kalibrator TERKUAT yang wajar (isotonik, dipasang pada OIA-DDR validasi),
   termasuk skor fusi. Tanpa itu gate menang hanya karena ia satu-satunya keluaran terlatih-NLL,
   dan klaimnya akan runtuh begitu reviewer menjalankan isotonik sendiri.

Keluaran: _FINAL_Latex/tables/S8_net_benefit.tex. Jalankan dari root repo.
"""
import json
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ISO = ROOT / "_septem/scripts_optionB/net_benefit_isotonic_check.json"
BS = ROOT / "_septem/scripts_optionB/net_benefit_bootstrap.json"
V2 = ROOT / "_septem/scripts_optionB/net_benefit_v2.json"
OUT = ROOT / "_FINAL_Latex/tables/S8_net_benefit.tex"

SYS = [("detector_score", "Detector score"), ("score_fusion", "Score fusion"),
       ("full_gate", "Full gate"), ("gate_on_fusion", "Gate on fusion")]


def q(v, nd=4):
    return str(Decimal(repr(float(v))).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))


iso = json.loads(ISO.read_text(encoding="utf-8"))
bs = json.loads(BS.read_text(encoding="utf-8"))
v2 = json.loads(V2.read_text(encoding="utf-8"))
PT = iso["pt_grid"]
if bs["pt_grid"] != PT:
    raise SystemExit("BERHENTI: grid p_t bootstrap dan isotonik tidak sama.")

conv = bs["contrasts"]["B_simetris"]
cons = bs["contrasts"]["A_konservatif"]
gate_col = bs["contrasts"]["C_gate_terpasang"]

rows = []
for i, p in enumerate(PT):
    # SEMUA angka dibungkus mode matematika. Versi pertama mencetak
    # "${v}$" lalu menempelkan "$^{\ast}$", menghasilkan "$$" yang di LaTeX
    # membuka mode display dan merusak tabel; nilai negatif serta interval
    # keyakinan juga tercetak di luar matematika sehingga minusnya jadi tanda hubung.
    cells = [rf"${iso['treat_all'][i]:+.4f}$"]
    for key, _ in SYS:
        cells.append(rf"${iso['curves'][f'{key}__iso'][i]:+.4f}$")
    lo, hi = conv["ci_lo"][i], conv["ci_hi"][i]
    star = r"^{\ast}" if conv["excludes_zero"][i] else ""
    delta = rf"${conv['observed'][i]:+.4f}{star}$ $[{lo:+.4f}, {hi:+.4f}]$"
    rows.append(rf"${p:.2f}$ & " + " & ".join(cells) + rf" & {delta} \\")

WORD = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven",
        8: "eight", 9: "nine", 10: "ten", 11: "eleven", 12: "twelve", 13: "thirteen",
        14: "fourteen", 15: "fifteen"}
cons_for = [p for i, p in enumerate(PT)
            if cons["excludes_zero"][i] and cons["observed"][i] > 0]
cons_against = [p for i, p in enumerate(PT)
                if cons["excludes_zero"][i] and cons["observed"][i] < 0]
n_gate_lose = gate_col["n_pt_excluding_zero"]
first_sig = next((p for i, p in enumerate(PT) if conv["excludes_zero"][i] and p >= 0.30), None)
n_cons = cons["n_pt_excluding_zero"]

tex = "\n".join([
    "% Generated by _septem/scripts_optionB/make_s8_net_benefit.py from frozen JSON;",
    "% do not edit by hand. Sources: net_benefit_isotonic_check.json + net_benefit_bootstrap.json",
    "% Do not use net_benefit.json (v1): its quantile thresholds lock net benefit at <= p_t.",
    "% Every system is given isotonic calibration on OIA-DDR validation, score fusion included.",
    r"\begin{table}[htbp]",
    r"\centering",
    (r"\caption{Net benefit on OIA-DDR test across threshold probabilities, where a detection is retained when its calibrated probability reaches $p_t$ and net benefit is "
     r"$\mathrm{TP}/n-(\mathrm{FP}/n)\,p_t/(1-p_t)$. Every system is calibrated by isotonic regression fitted on OIA-DDR validation; the last column is the difference "
     r"between the gate on fusion and score fusion, with a 95\% image-clustered bootstrap interval over 2{,}000 resamples.}"),
    r"\label{tab:net_benefit}",
    r"\footnotesize",
    r"\setlength{\tabcolsep}{3pt}",
    r"\resizebox{\textwidth}{!}{%",
    # 7 kolom: p_t, retain-all, skor detektor, fusi, gate penuh, gate-atas-fusi, selisih+CI.
    # Versi pertama mendeklarasikan 8 kolom sedangkan header dan data hanya mengisi 7.
    r"\begin{tabular}{@{}lcccccc@{}}",
    r"\toprule",
    (r"$p_t$ & Retain all & Detector & Score & Full & Gate on & "
     r"Gate on fusion $-$ fusion \\"),
    r" & & score & fusion & gate & fusion & (95\% CI) \\",
    r"\midrule",
    *rows,
    r"\bottomrule",
    r"\end{tabular}}",
    r"\\[2pt]",
    r"{\footnotesize $^{\ast}$Interval excludes zero.}",
    r"\end{table}",
    "",
])
OUT.write_text(tex, encoding="utf-8")
print(f"ditulis {OUT}")
print(f"gate terpasang di bawah fusi isotonik, CI kecualikan nol: "
      f"{n_gate_lose}/{len(PT)} titik p_t")
print(f"gate-atas-fusi unggul andal mulai p_t = {first_sig}")
print(f"kontras konservatif: {n_cons}/{len(PT)} titik CI kecualikan nol")
