#!/usr/bin/env python
"""Generate the two conditional-coverage tables of the main article from frozen JSON.

No fitting, no recomputation: reads
  _LGOVNET_NEW_SEP/results/step0_conditional_coverage.json
  _LGOVNET_NEW_SEP/results/step1_conditional_coverage_cohorts.json
and writes
  _FINAL_Latex/tables/T16_conditional_coverage_indomain.tex
  _FINAL_Latex/tables/T17_conditional_coverage_cohorts.tex
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "_LGOVNET_NEW_SEP/results"
TAB = ROOT / "_FINAL_Latex/tables"
BS = chr(92)


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:16]


def g(x: float) -> str:
    return f"${x:+.3f}$".replace("+", r"+").replace("-", r"-")


def build_indomain() -> str:
    p = RES / "step0_conditional_coverage.json"
    d = json.loads(p.read_text(encoding="utf-8"))
    st = d["strata_test"]
    order = ["S (detector score)", "S+E (full gate)", "E5 (five detectors)",
             "E6 (six detectors)"]
    label = {"S (detector score)": "Detector score ($M_0$)",
             "S+E (full gate)": "Full gate, CEG-Net$^{\\dagger}$",
             "E5 (five detectors)": "Ensemble of five detectors",
             "E6 (six detectors)": "Ensemble of six detectors"}
    L = []
    A = L.append
    A(f"% Generated by _LGOVNET_NEW_SEP/scripts/make_conditional_coverage_tables.py")
    A(f"% Source: {p.relative_to(ROOT).as_posix()}  sha256[:16] = {sha(p)}")
    A(f"% Protocol locked before the run: {d['protocol']}")
    verdict = {"LANJUT": "PROCEED", "MATI": "STOP", "ABU-ABU": "GREY"}.get(
        d["verdict"], d["verdict"])
    A(f"% Verdict recorded in the JSON: {verdict}")
    A(r"\begin{table}[t]")
    A(r"\centering")
    A(r"\caption{Conditional coverage across corroboration strata on OIA-DDR test. "
      r"A split-conformal threshold is calibrated \emph{marginally} on OIA-DDR validation "
      r"at a nominal true-positive retention of 0.80 and applied unchanged, and each entry is "
      r"the empirical coverage inside a stratum minus 0.80. The stratum index $k$ counts "
      r"how many of five independently trained detectors place a box on the same candidate "
      r"at $\mathrm{IoU}\geq 0.15$, so it uses no annotation.}")
    A(r"\label{tab:cond_coverage_indomain}")
    A(r"\footnotesize")
    A(r"\setlength{\tabcolsep}{4pt}")
    A(r"\resizebox{\textwidth}{!}{%")
    A(r"\begin{tabular}{lrrrrrrr}")
    A(r"\toprule")
    A(r" & \multicolumn{1}{c}{Marginal} & \multicolumn{6}{c}{Coverage gap within stratum $k$} \\")
    A(r"\cmidrule(lr){2-2}\cmidrule(lr){3-8}")
    A(r"Method & gap & $k{=}0$ & $k{=}1$ & $k{=}2$ & $k{=}3$ & $k{=}4$ & $k{=}5$ \\")
    A(r"\midrule")
    A("Detections ($n$) & " + f"{d['strata_test']['0']['n'] + sum(st[str(k)]['n'] for k in range(1, 6)):,}".replace(",", "{,}")
      + " & " + " & ".join(f"{st[str(k)]['n']:,}".replace(",", "{,}") for k in range(6)) + r" \\")
    A("Positive targets & " + f"{sum(st[str(k)]['n_positive'] for k in range(6)):,}".replace(",", "{,}")
      + " & " + " & ".join(f"{st[str(k)]['n_positive']:,}".replace(",", "{,}") for k in range(6)) + r" \\")
    A("Positive rate & --- & " + " & ".join(f"{st[str(k)]['positive_rate']:.3f}" for k in range(6)) + r" \\")
    A(r"\midrule")
    for m in order:
        rec = d["methods"][m]
        cells = []
        for k in range(6):
            v = rec["per_stratum"][str(k)]
            cells.append(g(v["gap"]))
        A(f"{label[m]} & {g(rec['marginal_gap'])} & " + " & ".join(cells) + r" \\")
    A(r"\bottomrule")
    A(r"\end{tabular}}")
    A(r"\par\smallskip{\footnotesize $^{\dagger}$Mean over the five gate-initialization "
      r"seeds. The locked criterion to proceed was an absolute gap above 0.15 in a stratum "
      r"holding at least 200 positive targets, and the largest observed is "
      f"{d['max_abs_gap_eligible_strata']:.3f}" r".}")
    A(r"\end{table}")
    return "\r\n".join(L) + "\r\n"


def build_cohorts() -> str:
    p = RES / "step1_conditional_coverage_cohorts.json"
    d = json.loads(p.read_text(encoding="utf-8"))
    cohorts = list(d["cohorts"])
    taxes = [("A_corroboration", "Secondary detector corroborates the box"),
             ("B_prior_conflict", r"Runner-up class crosses a severity level ($\mathrm{SDCA}\geq\delta$)"),
             ("C_pss_availability", "Perturbation stability is measured")]
    order = ["S (detector score)", "M (top1-top2 margin)", "KG gate", "S+E (full gate)"]
    label = {"S (detector score)": "Detector score ($M_0$)",
             "M (top1-top2 margin)": "Top-1$-$top-2 margin",
             "KG gate": "Knowledge-graph gate$^{\\dagger}$",
             "S+E (full gate)": "Full gate, CEG-Net$^{\\dagger}$"}
    L = []
    A = L.append
    A(f"% Generated by _LGOVNET_NEW_SEP/scripts/make_conditional_coverage_tables.py")
    A(f"% Source: {p.relative_to(ROOT).as_posix()}  sha256[:16] = {sha(p)}")
    A(f"% Protocol locked before the run: {d['protocol']}")
    c = d["criteria"]
    A(f"% Locked criteria: C1={c['C1_diagnostic']['met']} "
      f"C2={c['C2_gate_beats_score_on_A']['met']} ({c['C2_gate_beats_score_on_A']['cohorts_won']}/4) "
      f"C3={c['C3_margin_survives_conditioning']['met']} "
      f"({c['C3_margin_survives_conditioning']['cohorts_won']}/2)")
    A(r"\begin{table}[t]")
    A(r"\centering")
    A(r"\caption{Worst-stratum coverage gap on four cohorts, under three annotation-free "
      r"stratifications. The same marginally calibrated split-conformal threshold of "
      r"Table~\ref{tab:selective_conformal} is applied unchanged, and each entry is the largest "
      r"absolute gap between the delivered and the intended 0.80 retention over the two "
      r"strata of that taxonomy, counting only strata with at least 200 positive targets. "
      r"Lower is better. The "
      r"marginal gap of each method is repeated for reference.}")
    A(r"\label{tab:cond_coverage_cohorts}")
    A(r"\footnotesize")
    A(r"\setlength{\tabcolsep}{4pt}")
    A(r"\resizebox{\textwidth}{!}{%")
    A(r"\begin{tabular}{l" + "rr" * 4 + r"}")
    A(r"\toprule")
    A(r" & " + " & ".join(r"\multicolumn{2}{c}{" + c + "}" for c in cohorts) + r" \\")
    A(" ".join(r"\cmidrule(lr){" + f"{2*i+2}-{2*i+3}" + "}" for i in range(4)))
    A(r"Method & " + " & ".join(r"marg. & worst" for _ in cohorts) + r" \\")
    for tax, title in taxes:
        A(r"\midrule")
        A(r"\multicolumn{9}{l}{\textit{" + title + r"}} \\")
        for m in order:
            cells = []
            for coh in cohorts:
                rec = d["cohorts"][coh]["taxonomies"][tax]["methods"][m]
                cells.append(g(rec["marginal_gap"]))
                w = rec["worst_eligible_abs_gap"]
                cells.append(f"{w:.3f}")
            A(f"{label[m]} & " + " & ".join(cells) + r" \\")
    A(r"\bottomrule")
    A(r"\end{tabular}}")
    A(r"\par\smallskip{\footnotesize $^{\dagger}$Mean over the five gate-initialization "
      r"seeds. Of the three pre-registered "
      r"criteria, the diagnostic one is met, the criterion that the full gate is more "
      r"uniform than raw confidence on the corroboration taxonomy is not met in any cohort, "
      r"and the criterion that the margin keeps its advantage under conditioning is met on "
      r"both cohorts where it was tested.}")
    A(r"\end{table}")
    return "\r\n".join(L) + "\r\n"


def main() -> None:
    TAB.mkdir(parents=True, exist_ok=True)
    (TAB / "T16_conditional_coverage_indomain.tex").write_text(
        build_indomain(), encoding="utf-8", newline="")
    (TAB / "T17_conditional_coverage_cohorts.tex").write_text(
        build_cohorts(), encoding="utf-8", newline="")
    print("wrote T16_conditional_coverage_indomain.tex and "
          "T17_conditional_coverage_cohorts.tex")


if __name__ == "__main__":
    main()
