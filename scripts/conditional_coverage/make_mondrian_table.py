#!/usr/bin/env python
"""Generate the Mondrian-preview supplementary table from frozen JSON. No fitting."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "_LGOVNET_NEW_SEP/results"
OUT = ROOT / "_FINAL_Latex/tables/S18_mondrian_preview.tex"


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:16]


def main() -> None:
    p0 = RES / "step0_conditional_coverage.json"
    p1 = RES / "step1_conditional_coverage_cohorts.json"
    d0 = json.loads(p0.read_text(encoding="utf-8"))
    d1 = json.loads(p1.read_text(encoding="utf-8"))
    cohorts = list(d1["mondrian_preview"])
    taxes = [("A_corroboration", "Secondary detector corroborates"),
             ("B_prior_conflict", "Runner-up crosses a severity level"),
             ("C_pss_availability", "Perturbation stability measured")]
    order = ["S (detector score)", "M (top1-top2 margin)", "KG gate", "S+E (full gate)"]
    label = {"S (detector score)": "Detector score ($M_0$)",
             "M (top1-top2 margin)": "Top-1$-$top-2 margin",
             "KG gate": "Knowledge-graph gate",
             "S+E (full gate)": "Full gate, CEG-Net"}
    L = []
    A = L.append
    A("% Generated by _LGOVNET_NEW_SEP/scripts/make_mondrian_table.py from frozen JSON.")
    A(f"% Sources: step0 sha256[:16] = {sha(p0)}; step1 sha256[:16] = {sha(p1)}")
    A("% Exploratory: declared a secondary outcome in both protocol locks; not a criterion.")
    A(r"\begin{table}[htbp]")
    A(r"\centering")
    A(r"\caption{Mondrian preview: worst-stratum coverage gap when the split-conformal "
      r"threshold is calibrated \emph{within} each stratum on OIA-DDR validation instead of "
      r"marginally, then applied unchanged. Lower is better. Compare against the marginal "
      r"columns of the corresponding table in the main article. This analysis is "
      r"exploratory.}")
    A(r"\label{tab:mondrian_preview}")
    A(r"\footnotesize")
    A(r"\setlength{\tabcolsep}{5pt}")
    A(r"\begin{tabular}{l" + "r" * len(cohorts) + r"}")
    A(r"\toprule")
    A(r"Method & " + " & ".join(cohorts) + r" \\")
    for tax, title in taxes:
        A(r"\midrule")
        A(r"\multicolumn{" + str(len(cohorts) + 1) + r"}{l}{\textit{" + title + r"}} \\")
        for m in order:
            cells = []
            for coh in cohorts:
                v = d1["mondrian_preview"][coh].get(tax, {}).get(m)
                cells.append(f"{v:.3f}" if v is not None else "---")
            A(f"{label[m]} & " + " & ".join(cells) + r" \\")
    A(r"\midrule")
    A(r"\multicolumn{" + str(len(cohorts) + 1) +
      r"}{l}{\textit{Six corroboration strata, OIA-DDR only}} \\")
    m0 = d0["mondrian_preview"]
    pad = " & ".join(["---"] * (len(cohorts) - 1))
    for key, lab in [("S (detector score)", "Detector score ($M_0$)"),
                     ("S+E (full gate)", "Full gate, CEG-Net"),
                     ("E5 (five detectors)", "Ensemble of five detectors"),
                     ("E6 (six detectors)", "Ensemble of six detectors")]:
        v = m0.get(key, {}).get("max_abs_gap")
        A(f"{lab} & " + (f"{v:.3f}" if v is not None else "---") + " & " + pad + r" \\")
    A(r"\bottomrule")
    A(r"\end{tabular}")
    A(r"\end{table}")
    OUT.write_text("\r\n".join(L) + "\r\n", encoding="utf-8", newline="")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
