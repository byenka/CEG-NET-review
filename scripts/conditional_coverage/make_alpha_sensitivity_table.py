#!/usr/bin/env python
"""Generate the miscoverage-level sensitivity table of the supplementary from frozen JSON.

No fitting, no recomputation: reads
  _LGOVNET_NEW_SEP/results/step7_alpha_sensitivity.json
and writes
  _FINAL_Latex/tables/S24_alpha_sensitivity.tex
The table is typeset at the end of Supplementary S14.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path


def _resolve(*candidates):
    """Find the input in the research workspace layout or in the repository layout."""
    for base in Path(__file__).resolve().parents:
        for rel in candidates:
            p = base / rel
            if p.exists():
                return p, base
    raise SystemExit("input not found: " + " or ".join(candidates))


SRC, ROOT = _resolve("_LGOVNET_NEW_SEP/results/step7_alpha_sensitivity.json",
                     "results/conditional_coverage/step7_alpha_sensitivity.json")
TAB = ROOT / "_FINAL_Latex/tables"
# Workspace name of the source folder, so that both layouts write the same comment;
# the hash printed beside it identifies the content.
SRC_LABEL = "_LGOVNET_NEW_SEP/results"
M0, B4, B6 = "M0_score", "KG-gate-MLP (ours)", "KG-gate+SDS+corrob (B6)"
NAMES = {"OIA-DDR test": "OIA-DDR", "IDRiD": "IDRiD", "TJDR": "TJDR", "FGADR": "FGADR"}


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:16]


def g(x: float) -> str:
    return f"${x:+.3f}$"


def build() -> str:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    assert d["status"] == "valid", d["status"]
    alphas = [f"{a:.2f}" for a in d["alphas"]]
    L = []
    A = L.append
    A("% Generated by _LGOVNET_NEW_SEP/scripts/make_alpha_sensitivity_table.py")
    A(f"% Source: {SRC_LABEL}/{SRC.name}  sha256[:16] = {sha(SRC)}")
    A(f"% Protocol locked before the run: {d['protocol']}  sha256 = {d['protocol_sha256']}")
    A(f"% P1 (full gate closer than M0 in the 8 cells at alpha 0.10 and 0.30): "
      f"k = {d['P1_full_gate']['k']}/8, met = {d['P1_full_gate']['met']}")
    A(r"\begin{table}[htbp]")
    A(r"\centering")
    A(r"\caption{Coverage gap at three miscoverage levels $\alpha$, under the threshold rule and calibration of "
      r"the main article. Gate gaps average five seeds, and the last column gives the paired image-clustered "
      r"95\% interval. Negative differences favor the full gate.}")
    A(r"\label{tab:alpha_sensitivity}")
    A(r"\footnotesize")
    A(r"\setlength{\tabcolsep}{4pt}")
    A(r"\begin{tabular}{llrrrc}")
    A(r"\toprule")
    A(r" & & \multicolumn{3}{c}{Coverage gap} & \\")
    A(r"\cmidrule(lr){3-5}")
    A(r"Dataset & $\alpha$ & Detector score & KG gate & Full gate & $|g_{\mathrm{full}}|-|g_{M_0}|$ (95\% CI) \\")
    A(r"\midrule")
    cohorts = list(d["cohorts"])
    for j, coh in enumerate(cohorts):
        for i, a in enumerate(alphas):
            r = d["cohorts"][coh]["alphas"][a]
            adv = r["abs_gap_advantage"][B6]
            lo, hi = adv["ci95"]
            name = NAMES[coh] if i == 0 else ""
            A(f"{name} & {a} & {g(r['gap'][M0])} & {g(r['gap'][B4])} & {g(r['gap'][B6])} & "
              f"{g(adv['point'])} [{g(lo)}, {g(hi)}] \\\\")
        if j < len(cohorts) - 1:
            A(r"\midrule")
    A(r"\bottomrule")
    A(r"\end{tabular}")
    A(r"\end{table}")
    return "\n".join(L) + "\n"


def main() -> None:
    TAB.mkdir(parents=True, exist_ok=True)
    (TAB / "S24_alpha_sensitivity.tex").write_text(build(), encoding="utf-8")
    print("wrote S24_alpha_sensitivity.tex")


if __name__ == "__main__":
    main()
