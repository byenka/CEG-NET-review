"""make_s9_source_domain_sensitivity.py — tabel suplemen S9 dari source_domain_sensitivity.json.

Isi: apakah hasil gating artefak karena gate SELALU dipasang di OIA-DDR validasi? Gate dipasang
pada kohort SUMBER yang berbeda lalu diuji pada target yang tetap, OIA-DDR test. Baris OIA-DDR
valid adalah KONTROL POSITIF: ia harus mereproduksi Tabel 2.

KRITERIA PRA-REGISTRASI TERPENUHI. Confound yang wajib ikut dilaporkan: prevalensi sumber berbeda
jauh, sehingga ini menguji pergeseran domain DAN pergeseran prior kelas sekaligus.

Keluaran: _FINAL_Latex/tables/S9_source_domain_sensitivity.tex. Jalankan dari root repo.
"""
import json
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "_septem/scripts_optionB/source_domain_sensitivity.json"
OUT = ROOT / "_FINAL_Latex/tables/S9_source_domain_sensitivity.tex"

LABEL = {"OIA-DDR valid": r"OIA-DDR validation\,\textsuperscript{c}",
         "FGADR train": "FGADR train", "TJDR test": "TJDR test"}


def q(v, nd=3):
    return str(Decimal(repr(float(v))).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))


d = json.loads(SRC.read_text(encoding="utf-8"))
if not d["verdict"]["criterion_met"]:
    raise SystemExit("BERHENTI: JSON menyatakan kriteria TIDAK terpenuhi, tetapi caption tabel ini "
                     "ditulis untuk kriteria terpenuhi. Periksa ulang sebelum melanjutkan.")

m0 = d["m0_ap"]
n_seeds = len(d["sources"][0]["gates"]["full_gate"]["ap_per_seed"])
rows = []
for s in d["sources"]:
    kg, fg = s["gates"]["kg_gate"], s["gates"]["full_gate"]
    # Pemisah ribuan diterapkan HANYA pada angka citra. Versi pertama memakai
    # .replace(",", "{,}", 1) pada SELURUH baris, sehingga koma pertama yang terkena
    # bukan pemisah ribuan melainkan thin-space LaTeX "\," di dalam label OIA-DDR,
    # yang berubah menjadi "\{,}" dan merusak LaTeX. Ini pengulangan bug yang sama
    # seperti di make_s6_clinical_cost_external.py.
    img = f"{s['n_images']:,}".replace(",", "{,}")
    rows.append(
        rf"{LABEL.get(s['name'], s['name'])} & {img} & {q(s['prevalence'])} & "
        rf"${kg['gain_vs_m0_mean']:+.4f}$ & {kg['n_gain_pos']}/{n_seeds} & "
        rf"${fg['gain_vs_m0_mean']:+.4f}$ & {fg['n_gain_pos']}/{n_seeds} & "
        rf"{fg['n_ci_above_0']}/{n_seeds} \\"
    )

ext = [s for s in d["sources"] if not s["name"].startswith("OIA-DDR")]
worst_ext = min(s["gates"]["full_gate"]["gain_vs_m0_mean"] for s in ext)
ctrl = next(s for s in d["sources"] if s["name"].startswith("OIA-DDR"))
prev_gap = max(abs(s["prevalence"] - d["prevalence_target"]) for s in ext)
n_ci_total = sum(s["gates"]["full_gate"]["n_ci_above_0"] for s in d["sources"])
n_ci_max = n_seeds * len(d["sources"])

tex = "\n".join([
    "% Generated by _septem/scripts_optionB/make_s9_source_domain_sensitivity.py from frozen",
    "% JSON; do not edit by hand. Source: _septem/scripts_optionB/source_domain_sensitivity.json",
    "% The gate is fitted on a different SOURCE cohort and tested on a FIXED target (OIA-DDR test).",
    "% The OIA-DDR validation row is the positive control and must reproduce the in-domain table.",
    r"\begin{table}[htbp]",
    r"\centering",
    (r"\caption{Sensitivity of the gating result to the cohort the gate is fitted on: every row fits the gate on a different source cohort and evaluates it on the same fixed "
     rf"target, OIA-DDR test, where the detector score reaches an AUPRC of {q(m0, 4)}. $\Delta$AUPRC is the mean gain over that score across {n_seeds} seeds; the seed "
     r"columns count seeds with a positive gain and seeds whose 95\% image-clustered bootstrap interval excludes zero.}"),
    r"\label{tab:source_domain_sensitivity}",
    r"\footnotesize",
    r"\setlength{\tabcolsep}{3pt}",
    r"\resizebox{\textwidth}{!}{%",
    # 8 kolom: label, citra, prevalensi, kg gain, kg seed, fg gain, fg seed, fg CI.
    # Versi pertama mendeklarasikan 7 kolom sedangkan baris data mengisi 8.
    r"\begin{tabular}{@{}lccccccc@{}}",
    r"\toprule",
    (r"Source cohort for the gate & Images & Positive & "
     r"\multicolumn{2}{c}{Knowledge-graph gate} & \multicolumn{3}{c}{Full gate} \\"),
    r"\cmidrule(lr){4-5}\cmidrule(lr){6-8}",
    (r" & & rate & $\Delta$AUPRC & seeds\,\textsuperscript{a} & $\Delta$AUPRC & "
     r"seeds\,\textsuperscript{a} & CI\,\textsuperscript{b} \\"),
    r"\midrule",
    *rows,
    r"\bottomrule",
    r"\end{tabular}}",
    r"\\[2pt]",
    (r"{\footnotesize \textsuperscript{a}Seeds with a positive gain. "
     r"\textsuperscript{b}Seeds whose 95\% interval excludes zero (2{,}000 resamples). "
     # Label in-domain yang BENAR adalah tab:governance (T2_governance_main.tex).
     # Versi pertama merujuk tab:indomain, yang tidak pernah ada di naskah mana pun dan
     # akan muncul sebagai tanda tanya di PDF.
     r"\textsuperscript{c}Positive control: this row reproduces the in-domain table of the main article.}"),
    r"\end{table}",
    "",
])
OUT.write_text(tex, encoding="utf-8")
print(f"ditulis {OUT}")
print(f"kriteria terpenuhi = {d['verdict']['criterion_met']}")
print(f"M0 AP = {m0:.5f}")
for s in d["sources"]:
    fg = s["gates"]["full_gate"]
    print(f"  {s['name']:16s} citra {s['n_images']:5d} prev {s['prevalence']:.4f} "
          f"full_gate AP {fg['ap_mean']:.5f} gain {fg['gain_vs_m0_mean']:+.5f} "
          f"seed+ {fg['n_gain_pos']}/{n_seeds} CI>0 {fg['n_ci_above_0']}/{n_seeds}")
