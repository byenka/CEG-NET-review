"""make_s6_clinical_cost_external.py — tabel suplemen S6 dari clinical_cost_external.json.

Isi: AUROC pemisahan konfusi grade-shifting (UNSAFE_MISMATCH) dari within-grade
(CLINICALLY_CLOSE_MISMATCH) untuk tiga sinyal, pada keempat kohort. Menjawab keberatan bahwa
klaim kebutaan biaya klinis hanya bertumpu pada satu dataset.

Keluaran: _FINAL_Latex/tables/S6_clinical_cost_external.tex. Jalankan dari root repo.
"""
import json
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "_septem/scripts_optionB/clinical_cost_external.json"
OUT = ROOT / "_FINAL_Latex/tables/S6_clinical_cost_external.tex"

ORDER = ["OIA-DDR", "IDRiD", "TJDR", "FGADR"]
LABEL = {"OIA-DDR": "OIA-DDR (in-domain)", "IDRiD": "IDRiD (zero-shot)",
         "TJDR": "TJDR (zero-shot)", "FGADR": "FGADR (zero-shot)"}


def q(v, nd=3):
    return str(Decimal(repr(float(v))).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))


def cell(s):
    """AUROC dengan CI; tanda dagger bila CI memuat 0.5, yaitu tak terbedakan dari tanpa informasi."""
    lo, hi = s["ci95"]
    mark = r"$^{\dagger}$" if s.get("ci_contains_half") else ""
    return rf"{q(s['auroc'])}{mark} [{q(lo)}, {q(hi)}]"


d = json.loads(SRC.read_text(encoding="utf-8"))
by = {c["name"]: c for c in d["cohorts"]}
missing = [n for n in ORDER if n not in by]
if missing:
    raise SystemExit(f"BERHENTI: kohort tidak ada di JSON: {missing}")

# FGADR memakai fusi TIGA pass dari step 6 terkunci; nilai dua pass di JSON beku di atas sudah digantikan.
STEP6 = next(p for p in (ROOT / "_LGOVNET_NEW_SEP/results/step6_fgadr_three_pass.json",
                         ROOT / "results/conditional_coverage/step6_fgadr_three_pass.json") if p.exists())
_c3 = json.loads(STEP6.read_text(encoding="utf-8"))["fgadr_three_pass"]["C_grade_shifting_auroc"]
_fg = by["FGADR"]
assert (_c3["n_unsafe"], _c3["n_close"]) == (_fg["n_unsafe"], _fg["n_close"]), "populasi FGADR berbeda"
_fg["signals"] = {k: v for k, v in _fg["signals"].items() if not k.startswith("fused_")} | {
    "fused_3_pass": {"auroc": _c3["auroc"], "ci95": _c3["ci95"], "info_abs": abs(_c3["auroc"] - 0.5),
                     "ci_contains_half": _c3["ci95"][0] < 0.5 < _c3["ci95"][1]}}
_fg["n_pass_fusion"] = 3

rows, npass_note = [], {}
for name in ORDER:
    c = by[name]
    fkey = next(k for k in c["signals"] if k.startswith("fused_"))
    npass_note[name] = c["n_pass_fusion"]
    star = r"$^{\ast}$" if c["n_pass_fusion"] == 2 else ""
    # Pemisah ribuan diubah HANYA pada n_close. Versi pertama menerapkan .replace(",", "{,}")
    # ke seluruh baris, sehingga koma di dalam interval keyakinan ikut terkena dan
    # "[0.981, 1.000]" menjadi "[0.981{,} 1.000]".
    n_close_str = f"{c['n_close']:,}".replace(",", "{,}")
    rows.append(
        rf"{LABEL[name]} & {c['n_unsafe']} / {n_close_str} & "
        rf"{cell(c['signals']['detector_score'])} & {cell(c['signals'][fkey])}{star} & "
        rf"{cell(c['signals']['kg_sdca'])} \\"
    )

two_pass = [n for n in ORDER if npass_note[n] == 2]
star_note = ("" if not two_pass else
             rf"$^{{\ast}}$" + f"The {', '.join(two_pass)} secondary-detector cache is not "
             "available, so only a two-pass mean can be recomputed there. ")

tex = "\n".join([
    "% Generated by _septem/scripts_optionB/make_s6_clinical_cost_external.py from frozen JSON;",
    "% do not edit by hand. Source: _septem/scripts_optionB/clinical_cost_external.json; FGADR score fusion",
    "% (three-pass) from _LGOVNET_NEW_SEP/results/step6_fgadr_three_pass.json.",
    "% Same protocol as the in-domain clinical-cost table, repeated on all four cohorts.",
    "% AUROC with the grade-shifting category as the positive class; 0.5 is no rank discrimination.",
    r"\begin{table}[htbp]",
    r"\centering",
    (r"\caption{Clinical-cost separability across all four cohorts: for each signal the table gives the AUROC for ranking grade-shifting confusions above within-grade "
     r"ones, with a 95\% image-clustered bootstrap interval. A value of 0.5 indicates no net rank discrimination, $\dagger$ marks an interval that contains 0.5, and "
     rf"score fusion is the ensembling baseline of the benchmark table of the main article. {star_note}}}"),
    r"\label{tab:clinical_cost_external}",
    r"\footnotesize",
    r"\setlength{\tabcolsep}{3pt}",
    r"\resizebox{\textwidth}{!}{%",
    r"\begin{tabular}{@{}llccc@{}}",
    r"\toprule",
    r"Cohort & $n$ unsafe / close & Detector score & Score fusion & KG SDCA \\",
    r"\midrule",
    *rows,
    r"\bottomrule",
    r"\end{tabular}}",
    r"\end{table}",
    "",
])
OUT.write_text(tex, encoding="utf-8")
print(f"ditulis {OUT}")
for name in ORDER:
    c = by[name]
    fkey = next(k for k in c["signals"] if k.startswith("fused_"))
    print(f"  {name:8s} skor {c['signals']['detector_score']['info_abs']:.4f}  "
          f"fusi {c['signals'][fkey]['info_abs']:.4f}  "
          f"sdca {c['signals']['kg_sdca']['info_abs']:.4f}  (|AUROC-0.5|)")
