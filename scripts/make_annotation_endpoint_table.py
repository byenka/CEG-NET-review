#!/usr/bin/env python
"""make_annotation_endpoint_table.py — render S12 dari JSON beku endpoint anotasi.

Tidak memasang model dan tidak menghitung ulang apa pun. Seluruh angka dibaca dari
_NATIVE/results/annotation_endpoint.json, yang dihasilkan oleh
_NATIVE/scripts/annotation_endpoint_experiment.py di bawah protokol terkunci
_NATIVE/PROTOCOL_LOCK_annotation_endpoint.md.

Keluaran: _FINAL_Latex/tables/S12_annotation_endpoint.tex

Jalankan dari root repo:
  python _NATIVE/scripts/make_annotation_endpoint_table.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

def _resolve(*candidates):
    """Cari berkas masukan di beberapa tata letak: workspace riset dan paket unggah."""
    for base in Path(__file__).resolve().parents:
        for rel in candidates:
            p = base / rel
            if p.exists():
                return p, base
    raise SystemExit("masukan tidak ditemukan: " + " atau ".join(candidates))


SRC, ROOT = _resolve("_NATIVE/results/annotation_endpoint.json",
                     "results/experiments/annotation_endpoint.json")
_TABLES = ROOT / "_FINAL_Latex/tables" if (ROOT / "_FINAL_Latex/tables").is_dir() else ROOT / "tables"
OUT = _TABLES / "S12_annotation_endpoint.tex"

COHORTS = ["OIA-DDR test", "IDRiD", "TJDR", "FGADR"]
LABEL = {"OIA-DDR test": "OIA-DDR test", "IDRiD": "IDRiD", "TJDR": "TJDR", "FGADR": "FGADR"}


def f3(x: float) -> str:
    return f"{x:.3f}"


def ci3(lo: float, hi: float) -> str:
    return f"[{lo:.3f}, {hi:.3f}]"


def signed3(x: float) -> str:
    return f"$+{x:.3f}$" if x >= 0 else f"$-{abs(x):.3f}$"


def signed_ci3(lo: float, hi: float) -> str:
    def one(v: float) -> str:
        return f"+{v:.3f}" if v >= 0 else f"-{abs(v):.3f}"
    return f"$[{one(lo)}, {one(hi)}]$"


def thousands(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    res = d["results"]
    digest = hashlib.sha256(SRC.read_bytes()).hexdigest()[:16]

    rows = []
    for c in COHORTS:
        r = res[c]
        auc = r["sdca_auc_ci"]
        inc = r["incremental_over_margin"]
        odds = r["odds_ratio_delta030"]
        ps = r["per_signal"]
        star = "$^{*}$" if auc["excludes_half"] else ""
        rows.append(
            " & ".join([
                LABEL[c],
                thousands(r["n_localized"]),
                f3(r["mismatch_rate"]),
                f3(odds["rate_low"]),
                f3(odds["rate_high"]),
                f3(ps["SDCA"]["auroc"]) + star,
                ci3(*auc["ci95"]),
                f3(ps["PERM"]["auroc"]),
                f3(ps["EMP"]["auroc"]),
                f3(ps["MARGIN"]["auroc"]),
                signed3(inc["delta_auroc"]),
                signed_ci3(*inc["ci95"]),
            ]) + r" \\"
        )

    caption = (
        "Annotation-grounded validation of the prior on detections that localize an annotated "
        "lesion at $\\mathrm{IoU}\\geq 0.5$, with class mismatch as the outcome. MARGIN is the "
        "top-1 minus top-2 margin, PERM the permuted prior and EMP a relation estimated from "
        "OIA-DDR. An asterisk marks an image-clustered 95\\% interval that excludes 0.5."
    )

    header = (
        r"Cohort & $n$ & Mismatch & \multicolumn{2}{c}{By conflict group} & "
        r"\multicolumn{2}{c}{SDCA AUROC} & PERM & EMP & MARGIN & "
        r"\multicolumn{2}{c}{$\Delta$ over MARGIN} \\"
        "\n"
        r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){11-12}"
        "\n"
        r" & & rate & low & high & value & 95\% CI & AUROC & AUROC & AUROC & value & 95\% CI \\"
    )

    text = (
        "% Generated by _NATIVE/scripts/make_annotation_endpoint_table.py from frozen JSON;\n"
        "% no model fitting. Source: _NATIVE/results/annotation_endpoint.json\n"
        f"% sha256[:16] = {digest}\n"
        "% Protocol locked before the run: _NATIVE/PROTOCOL_LOCK_annotation_endpoint.md\n"
        "% Verdict recorded in the JSON: A1, A2 and A3 all fail; the prior is not validated.\n"
        "\\begin{table}[htbp]\n"
        "\\centering\n"
        "\\caption{" + caption + "}\n"
        "\\label{tab:annotation_endpoint}\n"
        "\\footnotesize\n"
        "\\setlength{\\tabcolsep}{3pt}\n"
        "\\resizebox{\\textwidth}{!}{%\n"
        "\\begin{tabular}{lrrrrrcrrrrc}\n"
        "\\toprule\n"
        + header + "\n"
        "\\midrule\n"
        + "\n".join(rows) + "\n"
        "\\bottomrule\n"
        "\\end{tabular}}\n"
        "\\end{table}\n"
    )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"ditulis {OUT}")
    print(f"sumber sha256[:16] = {digest}")
    for c in COHORTS:
        r = res[c]
        print(f"  {c:14s} n={r['n_localized']:6d} "
              f"SDCA={r['per_signal']['SDCA']['auroc']:.3f} "
              f"MARGIN={r['per_signal']['MARGIN']['auroc']:.3f} "
              f"OR={r['odds_ratio_delta030']['odds_ratio']:.3f}")


if __name__ == "__main__":
    main()
