"""make_s7_target_recalibration.py — tabel suplemen S7 dari target_recalibration.json.

Isi: apakah sedikit sampel berlabel dari domain target memulihkan titik kerja yang tidak
transfer? Tiga ambang dibandingkan pada bagian evaluasi yang SAMA: tau_sumber (dipilih pada
OIA-DDR valid, yang dipakai naskah), tau_target (dipilih pada separuh kohort target yang tidak
dievaluasi), tau_oracle (dipilih pada bagian evaluasi itu sendiri; batas atas yang tidak dapat
dicapai di penempatan nyata).

KRITERIA PRA-REGISTRASI TIDAK TERPENUHI dan tabel ini melaporkannya apa adanya. Angka SD dihitung
ulang dari per_seed di JSON, TIDAK disalin dari catatan mana pun.

Keluaran: _FINAL_Latex/tables/S7_target_recalibration.tex. Jalankan dari root repo.
"""
import json
import statistics
from decimal import ROUND_CEILING, ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "_septem/scripts_optionB/target_recalibration.json"
OUT = ROOT / "_FINAL_Latex/tables/S7_target_recalibration.tex"

ORDER = ["OIA-DDR", "IDRiD", "TJDR", "FGADR"]
LABEL = {"OIA-DDR": "OIA-DDR (in-domain)", "IDRiD": "IDRiD (zero-shot)",
         "TJDR": "TJDR (zero-shot)", "FGADR": "FGADR (zero-shot)"}
HALVES = ("A_cal_B_eval", "B_cal_A_eval")


def q(v, nd=3):
    return str(Decimal(repr(float(v))).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))


def qb(v, nd=3):
    """A stated bound must not round down, or the sentence becomes false."""
    return str(Decimal(repr(abs(float(v)))).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_CEILING))


def spread(cohort, which, field):
    """SD antar 10 bagian evaluasi (5 seed x 2 belahan), dihitung ulang dari per_seed."""
    vals = [r[h][which][field] for r in cohort["per_seed"] for h in HALVES]
    return statistics.stdev(vals)


d = json.loads(SRC.read_text(encoding="utf-8"))
by = {c["name"]: c for c in d["cohorts"]}
n_seeds = len(d["cohorts"][0]["per_seed"])
missing = [n for n in ORDER if n not in by]
if missing:
    raise SystemExit(f"BERHENTI: kohort tidak ada di JSON: {missing}")
if d["verdict"]["criterion_met"]:
    raise SystemExit("BERHENTI: JSON menyatakan kriteria TERPENUHI, tetapi caption tabel ini "
                     "ditulis untuk kriteria TIDAK terpenuhi. Periksa ulang sebelum melanjutkan.")

target = d["tp_ret_target"]
tol = d["tolerance"]
rows = []
for name in ORDER:
    c = by[name]
    half_imgs = c["n_images"] // 2
    sd_t = spread(c, "target", "tp_ret")
    gain = c["target"]["fp_supp_mean"] - c["source"]["fp_supp_mean"]
    rows.append(
        rf"{LABEL[name]} & {half_imgs} & "
        rf"{q(c['source']['tp_ret_mean'])} / {q(c['source']['fp_supp_mean'])} & "
        rf"{q(c['target']['tp_ret_mean'])} / {q(c['target']['fp_supp_mean'])} & "
        rf"{q(c['oracle']['tp_ret_mean'])} / {q(c['oracle']['fp_supp_mean'])} & "
        rf"${gain:+.3f}$ & {q(sd_t)} \\"
    )

ext = [by[n] for n in ORDER if n != "OIA-DDR"]
worst = max(c["target"]["abs_err_tp_mean"] for c in ext)
max_src_bias = max(abs(c["source"]["tp_ret_mean"] - target) for c in by.values())
max_tgt_bias = max(abs(c["target"]["tp_ret_mean"] - target) for c in by.values())

tex = "\n".join([
    "% Generated by _septem/scripts_optionB/make_s7_target_recalibration.py from frozen JSON;",
    "% do not edit by hand. Source: _septem/scripts_optionB/target_recalibration.json",
    "% Split by IMAGE, calibrate on one half, evaluate on the other, then swap, then",
    "% average over 5 seeds x 2 halves. The pre-registered criterion is NOT met.",
    r"\begin{table}[htbp]",
    r"\centering",
    (r"\caption{Recalibrating the operating point on the target domain. Cells give true-positive retention / "
     r"false-positive suppression at the target retention. $\tau_{\mathrm{source}}$ is selected on OIA-DDR validation, "
     r"$\tau_{\mathrm{target}}$ on the held-out half of the target cohort, and $\tau_{\mathrm{oracle}}$ on the "
     r"evaluation half itself, an upper bound.}"),
    r"\label{tab:target_recalibration}",
    r"\footnotesize",
    r"\setlength{\tabcolsep}{3pt}",
    r"\resizebox{\textwidth}{!}{%",
    r"\begin{tabular}{@{}lcccccc@{}}",
    r"\toprule",
    (r"Cohort & Calib.\ images & $\tau_{\mathrm{source}}$ & $\tau_{\mathrm{target}}$ & "
     r"$\tau_{\mathrm{oracle}}$ & $\Delta$FP-supp. & SD \\"),
    (r" & per half & TP ret.\ / FP supp. & TP ret.\ / FP supp. & TP ret.\ / FP supp. & "
     r"(target$-$source) & (TP ret.) \\"),
    r"\midrule",
    *rows,
    r"\bottomrule",
    r"\end{tabular}}",
    r"\end{table}",
    "",
])
OUT.write_text(tex, encoding="utf-8")
print(f"ditulis {OUT}")
print(f"kriteria terpenuhi = {d['verdict']['criterion_met']} (dilaporkan apa adanya)")
for name in ORDER:
    c = by[name]
    print(f"  {name:8s} bias sumber {c['source']['tp_ret_mean'] - target:+.3f}  "
          f"bias target {c['target']['tp_ret_mean'] - target:+.3f}  "
          f"dFPsup {c['target']['fp_supp_mean'] - c['source']['fp_supp_mean']:+.3f}  "
          f"SD {spread(c, 'target', 'tp_ret'):.3f}")
